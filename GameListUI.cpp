// Row geometry, icon size and visible-row count all live in g_M now (see
// ComputeUiMetrics) rather than in fixed #defines, so the layout adapts to a
// 640x480 back buffer instead of overflowing it.

static WORD CurrentButtons(); // defined with the other shared screen helpers below

// One loaded cover, plus the SOURCE image's aspect ratio. STFS thumbnails are
// usually square but the header doesn't promise it, and stretching a
// non-square one into a fixed square tile looks wrong - so DrawIconFitted
// letterboxes within a consistent tile box, which keeps rows aligned whatever
// shape the art turns out to be.
struct Icon
{
    D3DTexture *texture;
    D3DTexture *average; // 1x1: the image's average colour, which fills its tile
    float aspect; // source width / source height
};

// The average colour as a 1x1 texture, from decoded pixels. Transparent
// pixels count for nothing, so an icon on a clear background is averaged over
// the icon alone.
static D3DTexture *CreateAverageFromArgb(const unsigned long *pixels, unsigned long w, unsigned long h)
{
    double r = 0.0, g = 0.0, b = 0.0, weight = 0.0;
    for (unsigned long i = 0; i < w * h; ++i)
    {
        unsigned long c = pixels[i];
        double a = ((c >> 24) & 0xFF) / 255.0;
        r += ((c >> 16) & 0xFF) * a;
        g += ((c >> 8) & 0xFF) * a;
        b += (c & 0xFF) * a;
        weight += a;
    }
    if (weight <= 0.0)
        return NULL;

    unsigned long average = 0xFF000000 |
                            ((unsigned long)(r / weight) << 16) |
                            ((unsigned long)(g / weight) << 8) |
                            (unsigned long)(b / weight);
    return CreateTextureFromArgb(&average, 1, 1);
}

// Creates a texture from raw PNG/JPEG bytes, recording the source aspect.
// Leaves out->texture NULL on any failure, so callers can just fall through
// to the next source.
// whichImage and gameName are for diagnostics only. This used to fail
// silently - it returned false and the caller drew a placeholder, so a title
// with no cover looked identical whether the package had no artwork or D3DX
// had refused perfectly good artwork. Those need different fixes, and telling
// them apart from the screen is impossible.
static bool CreateIconTexture(const unsigned char *data, unsigned long size, Icon *out,
                              const char *whichImage, const char *gameName)
{
    if (data == NULL || size == 0)
        return false;

    // Aspect comes from the SOURCE image, not the created texture: D3DX may
    // round the texture up to power-of-two dimensions, and it resamples the
    // whole image into whatever it creates, so the texture's own size says
    // nothing about the original proportions while UV 0..1 still covers it.
    float aspect = 1.0f;
    D3DXIMAGE_INFO imgInfo;
    ZeroMemory(&imgInfo, sizeof(imgInfo));

    HRESULT hrInfo = D3DXGetImageInfoFromFileInMemory(data, size, &imgInfo);
    if (SUCCEEDED(hrInfo) && imgInfo.Height > 0)
        aspect = (float)imgInfo.Width / (float)imgInfo.Height;

    // MipLevels=1 and an explicit D3DFMT_A8R8G8B8 (not D3DX_DEFAULT /
    // D3DFMT_UNKNOWN) - matching g_pWhiteTexture's own known-working creation
    // parameters exactly. Letting D3DX auto-generate a full mip chain and
    // auto-detect the format from arbitrary image data is a plausible way to
    // end up with a texture the GPU's texture-fetch hardware stalls on -
    // confirmed necessary previously: the call stack for a GPU deadlock went
    // through Present() waiting on a resource fence that never signaled, only
    // once real (not placeholder) icon textures started getting drawn.
    // Explicit dimensions rather than D3DX_DEFAULT (which would keep the
    // source size), so one oversized thumbnail can't quietly cost far more
    // texture memory than a 60px tile can show. 128 leaves better than 2x
    // headroom over the largest size these are ever drawn at; raise it if the
    // tiles ever grow.
    //
    // Resampling to a square does NOT distort non-square art: the aspect
    // recorded above comes from the source image, and DrawIconFitted uses it
    // to draw into a correctly-proportioned rect, which undoes the squash.
    const UINT ICON_TEXTURE_SIZE = 128;

    D3DTexture *texture = NULL;
    HRESULT hr = D3DXCreateTextureFromFileInMemoryEx(
        g_pd3dDevice, data, size,
        ICON_TEXTURE_SIZE, ICON_TEXTURE_SIZE, 1, 0, D3DFMT_A8R8G8B8,
        D3DPOOL_MANAGED, D3DX_DEFAULT, D3DX_DEFAULT, 0, NULL, NULL, &texture);

    if (FAILED(hr) || texture == NULL)
    {
        // D3DX refused it - in practice because it's a palette-indexed PNG,
        // which neither D3DX nor XUI will decode (see PngDecode.h). Decode it
        // ourselves instead.
        unsigned long *pixels = NULL;
        unsigned long pngW = 0, pngH = 0;
        const char *pngError = NULL;

        if (PngDecodeToArgb(data, size, &pixels, &pngW, &pngH, &pngError))
        {
            texture = CreateTextureFromArgb(pixels, pngW, pngH);
            D3DTexture *average = (texture != NULL) ? CreateAverageFromArgb(pixels, pngW, pngH) : NULL;
            PngFree(pixels);

            if (texture != NULL)
            {
                // Logged on success too, so it's visible on hardware that the
                // fallback is what drew a given cover.
                dprintf("[icon] \"%s\" %s: D3DX refused it (0x%08lX); decoded in-house, %lux%lu colourType=%u\n",
                        gameName != NULL ? gameName : "?", whichImage != NULL ? whichImage : "?",
                        (unsigned long)hr, pngW, pngH, size > 25 ? (unsigned)data[25] : 0u);

                out->texture = texture;
                out->average = average;
                out->aspect = (float)pngW / (float)pngH;
                return true;
            }

            pngError = "decoded, but creating the texture failed";
        }

        // Both refused. The decoder's reason is specific ("image data is
        // truncated", "chunk runs past the end of the data", "not a PNG"...),
        // which is why the IHDR and IEND dumps that used to live here are
        // gone - they were a way of guessing at exactly this.
        unsigned long magic = 0;
        if (size >= 4)
        {
            magic = ((unsigned long)data[0] << 24) | ((unsigned long)data[1] << 16) |
                    ((unsigned long)data[2] << 8) | (unsigned long)data[3];
        }

        dprintf("[icon] \"%s\" %s: D3DX refused it (0x%08lX, size=%lu magic=%08lX); in-house decoder: %s\n",
                gameName != NULL ? gameName : "?", whichImage != NULL ? whichImage : "?",
                (unsigned long)hr, size, magic, pngError != NULL ? pngError : "?");

        return false;
    }

    out->texture = texture;
    out->aspect = aspect;

    // The average colour: D3DX shrinks the same image to a single texel,
    // which a triangle filter makes the average of the whole thing. No lock
    // needed - it's drawn as it is, stretched across the tile.
    out->average = NULL;
    D3DXCreateTextureFromFileInMemoryEx(g_pd3dDevice, data, size, 1, 1, 1, 0, D3DFMT_A8R8G8B8,
                                        D3DPOOL_MANAGED, D3DX_FILTER_TRIANGLE, D3DX_DEFAULT, 0,
                                        NULL, NULL, &out->average);
    return true;
}

// Draws a cover centred inside a boxSize x boxSize tile, preserving its
// aspect ratio rather than stretching it to fill.
static void DrawIconFitted(const Icon *icon, float boxX, float boxY, float boxSize)
{
    float w = boxSize;
    float h = boxSize;

    if (icon->aspect > 1.0f)
        h = boxSize / icon->aspect; // wider than tall
    else if (icon->aspect < 1.0f)
        w = boxSize * icon->aspect; // taller than wide

    DrawQuad(icon->texture,
             boxX + (boxSize - w) * 0.5f,
             boxY + (boxSize - h) * 0.5f,
             w, h, 0xFFFFFFFF);
}

// Cover art, loaded once and kept for the life of the UI.
//
// This used to be a local array built on entry and released on exit, which was
// fine when the list was shown exactly once. Now that it's the app's root
// screen and the user returns to it after every download, that meant
// re-reading and re-decoding the whole library - 27 STFS header reads and 27
// PNG decodes - every single time they backed out of a pack. Freed in
// ShutdownGameListUI.
static Icon *g_icons = NULL;
static int g_iconCount = 0;

static void ReleaseIcons()
{
    if (g_icons == NULL)
        return;

    for (int i = 0; i < g_iconCount; ++i)
    {
        if (g_icons[i].texture != NULL)
            g_icons[i].texture->Release();
        if (g_icons[i].average != NULL)
            g_icons[i].average->Release();
    }

    free(g_icons);
    g_icons = NULL;
    g_iconCount = 0;
}

void ReleaseGameListIcons()
{
    ReleaseIcons();
}

static void EnsureIconsLoaded(const InstalledGame *games, int gameCount)
{
    if (g_icons != NULL && g_iconCount == gameCount)
        return; // already loaded for this library

    ReleaseIcons();

    // Installed-game libraries on a modded 360 are realistically dozens, not
    // thousands, of titles, and each image is at most 16KB of source PNG, so
    // loading the lot up front is a bounded one-time cost rather than
    // something that needs lazy/scroll-triggered loading.
    g_icons = (Icon *)malloc(sizeof(Icon) * gameCount);
    if (g_icons == NULL)
        return;

    g_iconCount = gameCount;
    memset(g_icons, 0, sizeof(Icon) * gameCount);

    int fromStfs = 0, placeholders = 0;

    for (int i = 0; i < gameCount; ++i)
    {
        g_icons[i].texture = NULL;
        g_icons[i].average = NULL;
        g_icons[i].aspect = 1.0f;

        // The images the scan kept, so nothing is read from disk here. No
        // data means the package genuinely has none, while data that failed
        // means D3DX refused something that was there - the two need
        // opposite responses, so the placeholder report says which.
        const InstalledGame &game = games[i];
        const bool hadImageData = (game.titleThumbnail != NULL || game.contentThumbnail != NULL);

        if (game.titleThumbnail != NULL)
            CreateIconTexture(game.titleThumbnail, game.titleThumbnailSize, &g_icons[i],
                              "title thumbnail", game.displayName);

        // Second embedded image - GOD converters frequently leave the title
        // thumbnail zeroed while this one survives.
        if (g_icons[i].texture == NULL && game.contentThumbnail != NULL)
            CreateIconTexture(game.contentThumbnail, game.contentThumbnailSize, &g_icons[i],
                              "content thumbnail", game.displayName);

        if (g_icons[i].texture != NULL)
            fromStfs++;

        if (g_icons[i].texture == NULL)
        {
            // Name them. A bare count says three titles came up empty but not
            // WHICH three, and that's the part worth acting on - it's the
            // difference between "some GOD conversions dropped their
            // thumbnails" and "a whole content type isn't being handled".
            // Capped so a library that finds no art at all doesn't flood the
            // log.
            if (placeholders < 10)
                dprintf("  No cover art for \"%s\" (Title ID %08lX) - %s\n",
                        games[i].displayName, games[i].titleId,
                        hadImageData ? "package HAS artwork, but it could not be decoded (see [icon] lines above)"
                                     : "package carries no artwork");
            else if (placeholders == 10)
                dprintf("  (further titles without cover art not listed)\n");

            placeholders++;
        }
    }

    dprintf("Cover art: %d from package metadata, %d placeholder\n", fromStfs, placeholders);
}

// Clamps the selection into the list and moves scroll just far enough to keep
// it on screen. scroll < 0 means "not placed yet" and centres the selection,
// so a page opened on row 20 doesn't start scrolled to the top and snap.
static void KeepSelectionVisible(int count, int visibleRows, int &selected, int &scroll)
{
    // Upper clamp before lower: with an empty list the upper bound is -1, and
    // the row has to end up at 0, not -1.
    if (selected > count - 1) selected = count - 1;
    if (selected < 0) selected = 0;

    if (scroll < 0) scroll = selected - visibleRows / 2;
    if (selected < scroll) scroll = selected;
    if (selected >= scroll + visibleRows) scroll = selected - visibleRows + 1;
    if (scroll > count - visibleRows) scroll = count - visibleRows;
    if (scroll < 0) scroll = 0;
}

// A thin rounded scrollbar down the right edge of the page - only drawn when
// something is off-screen.
static void DrawScrollbar(float trackY, float trackH, int count, int visibleRows, int scroll)
{
    const float w = S(4.0f);
    const float x = g_M.contentX + g_M.contentW - w;

    float thumbH = trackH * ((float)visibleRows / (float)count);
    if (thumbH < S(24.0f)) thumbH = S(24.0f);

    // Positioned by scroll range, not item count, so the thumb lands flush at
    // the bottom on the last page.
    float thumbY = trackY + (trackH - thumbH) * ((float)scroll / (float)(count - visibleRows));

    FillRound(x, trackY, w, trackH, w * 0.5f, COL_SURFACE);
    FillRound(x, thumbY, w, thumbH, w * 0.5f, COL_TEXT2);
}

