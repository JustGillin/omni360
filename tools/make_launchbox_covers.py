"""
Builds LaunchBoxCovers.h from tools/data/launchbox-covers.txt - the LaunchBox
cover for each game Xbox Live and xboxunity have none for - and
tools/data/launchbox-indie-covers.txt, the indie games', sorted by key for
LaunchBoxCoverFile's binary search.

    python tools/make_launchbox_covers.py

A key is the game's title ID, or its name hashed as CoverArt.cpp's NameHash
does - FNV-1a over the lower-cased name, its low 24 bits - tagged 0xEC for a
Store game with no title ID ("name:") or 0xED for an indie game ("indie:").
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "tools", "data", "launchbox-covers.txt")
INDIE_DATA = os.path.join(ROOT, "tools", "data", "launchbox-indie-covers.txt")
OUT = os.path.join(ROOT, "src", "LaunchBoxCovers.h")
NAME_KEY_TAG = 0xEC000000
INDIE_KEY_TAG = 0xED000000


def name_key(name, tag=NAME_KEY_TAG):
    h = 2166136261
    for b in name.encode("utf-8"):
        if 65 <= b <= 90:
            b += 32
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return tag | (h & 0x00FFFFFF)


def main():
    rows = []
    note = ""
    lines = []
    for path in (DATA, INDIE_DATA):
        with open(path, encoding="utf-8") as f:
            lines += f.read().splitlines()
    if True:
        for line in lines:
            line = line.strip()
            if not line:
                continue
            if line.startswith("#"):
                note = line[1:].strip()
                continue
            key, _, file = line.partition(" = ")
            key = key.strip()
            if key.startswith("name:"):
                k = name_key(key[5:])
            elif key.startswith("indie:"):
                k = name_key(key[6:], INDIE_KEY_TAG)
            else:
                k = int(key, 16)
            rows.append((k, file.strip(), key if ":" in key[:6] else note))
    rows.sort()
    keys = [r[0] for r in rows]
    if len(set(keys)) != len(keys):
        raise SystemExit("two lines share a key")

    L = ["// GENERATED by tools/make_launchbox_covers.py from",
         "// tools/data/launchbox-covers.txt - do not edit by hand.",
         "//",
         "// LaunchBox covers for the games Xbox Live and xboxunity have none for, by",
         "// title ID or StoreNameCoverKey, sorted for a binary search.",
         "",
         "#ifndef LAUNCHBOX_COVERS_H",
         "#define LAUNCHBOX_COVERS_H",
         "",
         "struct LaunchBoxCover",
         "{",
         "    unsigned long key;",
         "    const char *file; // under https://images.launchbox-app.com/",
         "};",
         "",
         "static const LaunchBoxCover kLaunchBoxCovers[] =",
         "{"]
    for k, file, note in rows:
        L.append('    { 0x%08X, "%s" }, // %s' % (k, file, note.replace("\\", "/")))
    L += ["};", "", "#endif", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(L))
    print("%d covers" % len(rows))


if __name__ == "__main__":
    main()
