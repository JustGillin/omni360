"""Builds src/LanguagePacks.h from Languages/*.txt, and the files translators use.

    python tools/make_languages.py             # compile Languages/*.txt into the XEX
    python tools/make_languages.py --template  # rewrite Languages/TEMPLATE.txt from Strings.def
    python tools/make_languages.py --check fr  # what fr.txt is missing, extra or wrong
    python tools/make_languages.py --pseudo    # Languages/pseudo/xx.txt - see below

Each language is one UTF-8 file, Languages/<code>.txt, of "KEY = text" lines
with an "@name" line naming it in its own language. Strings.cpp reads the
same format from game:\\Languages\\ beside the XEX, so a file can be tried on
the console before it is compiled in. Languages/README.md says how to write
one.

The pseudo language is English with accents on every letter and a third
again on its length, in [brackets]. It shows, on the console, any text still
hardcoded in English (it has no accents and no brackets) and any label too
narrow for German or Russian (its end is cut off). It goes in a folder of
its own so the normal build never compiles it in; copy it to
game:\\Languages\\ to use it.

Run from the repo root.
"""

import codecs
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEF = os.path.join(ROOT, 'src', 'Strings.def')
LANG_DIR = os.path.join(ROOT, 'Languages')
OUTPUT = os.path.join(ROOT, 'src', 'LanguagePacks.h')
SKIP = {'TEMPLATE.txt', 'README.md'}

STR_LINE = re.compile(r'^STR\((\w+),\s*"((?:[^"\\]|\\.)*)"\)')
PLACEHOLDER = re.compile(r'\{[1-4]\}')


def c_string_to_text(s):
    """A C string literal's body (as written in Strings.def) to real text."""
    raw = codecs.escape_decode(s.encode('latin-1'))[0]
    return raw.decode('utf-8')


def read_def():
    entries = []
    for line in open(DEF, encoding='utf-8'):
        m = STR_LINE.match(line.strip())
        if m:
            entries.append((m.group(1), c_string_to_text(m.group(2))))
    return entries


def escape_value(text):
    return text.replace('\\', '\\\\').replace('\n', '\\n')


def unescape_value(text):
    out, i = [], 0
    while i < len(text):
        if text[i] == '\\' and i + 1 < len(text) and text[i + 1] in 'n\\':
            out.append('\n' if text[i + 1] == 'n' else '\\')
            i += 2
        else:
            out.append(text[i])
            i += 1
    return ''.join(out)


def read_language(path):
    """(name, {key: text}) - the same rules Strings.cpp parses by."""
    name, values = '', {}
    text = open(path, encoding='utf-8-sig').read()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, value = line.split('=', 1)
        key, value = key.strip(), value.strip()
        if key == '@name':
            name = value
        elif not key.startswith('@'):
            values[key] = unescape_value(value)
    return name, values


def language_files():
    if not os.path.isdir(LANG_DIR):
        return []
    return sorted(f for f in os.listdir(LANG_DIR)
                  if f.endswith('.txt') and f not in SKIP and os.path.isfile(os.path.join(LANG_DIR, f)))


def check(code, entries, quiet=False):
    """Prints what's wrong with a language; returns how many lines it translates."""
    path = os.path.join(LANG_DIR, code + '.txt')
    name, values = read_language(path)
    english = dict(entries)
    good = 0
    missing = [k for k, _ in entries if k not in values]
    extra = [k for k in values if k not in english]
    bad = [k for k in values if k in english and
           sorted(set(PLACEHOLDER.findall(values[k]))) != sorted(set(PLACEHOLDER.findall(english[k])))]
    good = len([k for k in values if k in english and k not in bad])
    if not quiet:
        print('%s (%s): %d of %d lines translated' % (code, name or 'no @name line', good, len(entries)))
        if not name:
            print('  no "@name = ..." line - the Settings list will show "%s"' % code)
        for k in bad:
            print('  placeholders differ, stays English: %s\n    en: %s\n    %s: %s' % (k, english[k], code, values[k]))
        for k in extra:
            print('  not a string Omni360 has (renamed or removed?): %s' % k)
        if missing:
            print('  %d missing, shown in English:' % len(missing))
            for k in missing:
                print('    %s = %s' % (k, escape_value(english[k])))
    return good


def write_template(entries):
    os.makedirs(LANG_DIR, exist_ok=True)
    path = os.path.join(LANG_DIR, 'TEMPLATE.txt')
    lines = [
        '# Omni360 - every string, in English. Copy this to <code>.txt (fr.txt,',
        '# de.txt, pt-br.txt...) and translate the text after each "=". See',
        '# README.md in this folder. Generated by tools/make_languages.py --template.',
        '',
        '@name = English',
        '',
    ]
    # Strings.def's section comments, carried over so the file reads by screen.
    section_re = re.compile(r'^// ---- (.*?) -*$')
    by_key = dict(entries)
    for line in open(DEF, encoding='utf-8'):
        s = line.strip()
        m = section_re.match(s)
        if m:
            lines += ['', '# ---- ' + m.group(1)]
            continue
        m = STR_LINE.match(s)
        if m:
            lines.append('%s = %s' % (m.group(1), escape_value(by_key[m.group(1)])))
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %s (%d strings)' % (os.path.relpath(path, ROOT), len(entries)))


ACCENTS = dict(zip('aceinousyACEINOUSYdDgGlLrRzZ',
                   'àçéîñöüšýÀÇÉÎÑÖÜŠÝđĐğĞłŁřŘžŽ'))


def pseudo(text):
    out, i = [], 0
    while i < len(text):
        m = PLACEHOLDER.match(text, i)
        if m:
            out.append(m.group(0))
            i = m.end()
            continue
        out.append(ACCENTS.get(text[i], text[i]))
        i += 1
    body = ''.join(out)
    pad = '~' * max(1, len(text) // 3)
    return '[' + body + pad + ']'


def write_pseudo(entries):
    folder = os.path.join(LANG_DIR, 'pseudo')
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, 'xx.txt')
    lines = ['# Pseudo language for testing - see tools/make_languages.py', '@name = [Pšéüđö]', '']
    lines += ['%s = %s' % (k, escape_value(pseudo(v))) for k, v in entries]
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %s - copy it to game:\\Languages\\xx.txt' % os.path.relpath(path, ROOT))


def c_bytes(text):
    """UTF-8 text, NUL-terminated, as a C array initialiser. A byte array
    rather than a string literal: the compiler caps literals at 64 KB, which
    a long translation in Cyrillic or CJK could pass."""
    data = text.encode('utf-8') + b'\0'
    rows = []
    for i in range(0, len(data), 24):
        rows.append('    ' + ','.join('0x%02X' % b for b in data[i:i + 24]) + ',')
    return '\n'.join(rows)


def write_header(entries):
    files = language_files()
    packs = []
    for f in files:
        code = f[:-4]
        good = check(code, entries, quiet=True)
        text = open(os.path.join(LANG_DIR, f), encoding='utf-8-sig').read()
        packs.append((code, text))
        print('  %s: %d of %d lines' % (code, good, len(entries)))

    out = [
        '// Generated by tools/make_languages.py from Languages/*.txt - do not edit.',
        '// Each is the language file as it is, parsed at run time by Strings.cpp.',
        '#pragma once',
        '',
        'struct LanguagePack',
        '{',
        '    const char *code;',
        '    const char *text;',
        '};',
        '',
        '#define LANGUAGE_PACK_COUNT %d' % len(packs),
        '',
    ]
    if packs:
        for n, (code, text) in enumerate(packs):
            out.append('// Languages/%s.txt' % code)
            out.append('static const char kLanguagePack%d[] =' % n)
            out.append('{')
            out.append(c_bytes(text))
            out.append('};')
            out.append('')
        out.append('static const LanguagePack kLanguagePacks[LANGUAGE_PACK_COUNT] =')
        out.append('{')
        for n, (code, _) in enumerate(packs):
            out.append('    { "%s", kLanguagePack%d },' % (code, n))
        out.append('};')
    else:
        out.append('static const LanguagePack kLanguagePacks[1] = { { "", "" } }; // none yet')
    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote %s (%d language%s)' % (os.path.relpath(OUTPUT, ROOT), len(packs), '' if len(packs) == 1 else 's'))


def main():
    # A Windows console's code page can't print most languages' text.
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    entries = read_def()
    args = sys.argv[1:]
    if '--template' in args:
        write_template(entries)
    elif '--pseudo' in args:
        write_pseudo(entries)
    elif '--check' in args:
        codes = args[args.index('--check') + 1:] or [f[:-4] for f in language_files()]
        for c in codes:
            check(c, entries)
    else:
        write_header(entries)


if __name__ == '__main__':
    main()
