# Regenerates src/MobCatTable.h from a titleIDs.db download.
# Usage: .\gen_mobcat_table.ps1 <path-to-titleIDs.db>
#
# Download the latest DB from: https://mobcat.zip/XboxIDs/titleIDs.db

param([string]$DbPath = "$env:USERPROFILE\Downloads\titleIDs.db")

$sqlite3 = Get-Command sqlite3 -ErrorAction SilentlyContinue
if (-not $sqlite3) { Write-Error "sqlite3.exe not found in PATH"; exit 1 }
if (-not (Test-Path $DbPath)) { Write-Error "DB not found: $DbPath"; exit 1 }

$rows = echo "SELECT Title_ID, XMID FROM TitleIDs WHERE Title_ID != '' AND XMID != '' ORDER BY Title_ID;" |
        sqlite3 $DbPath

$best = @{}
foreach ($row in $rows) {
    $parts = $row -split '\|'
    if ($parts.Count -lt 2) { continue }
    $tid  = $parts[0].Trim(); $xmid = $parts[1].Trim()
    if ($tid.Length -ne 8 -or $xmid.Length -lt 2) { continue }
    $region   = if ($xmid.Length -ge 8) { $xmid[-1] } else { 'Z' }
    $priority = switch ($region) { 'A' { 0 } 'W' { 1 } 'E' { 2 } default { 3 } }
    if (-not $best.ContainsKey($tid)) { $best[$tid] = @{ xmid = $xmid; pri = $priority } }
    elseif ($priority -lt $best[$tid].pri) { $best[$tid] = @{ xmid = $xmid; pri = $priority } }
}

$sorted = $best.GetEnumerator() | Sort-Object { [Convert]::ToUInt32($_.Key, 16) }

$lines = @(
    "// Auto-generated by tools/gen_mobcat_table.ps1 — do not edit.",
    "// Title ID -> XMID mapping from MobCat's original Xbox game list.",
    "// Used to fetch cover art and icons from:",
    "//   cover: raw.githubusercontent.com/.../cover/{XX}/{XMID}.jpg",
    "//   icon:  raw.githubusercontent.com/.../icon/{XXXXXXXX[0..3]}/{XXXXXXXX}.png",
    "#ifndef MOBCAT_TABLE_H",
    "#define MOBCAT_TABLE_H",
    "",
    "struct MobCatEntry { unsigned long titleId; char xmid[9]; };",
    "",
    "// $($sorted.Count) entries, sorted by titleId for binary search.",
    "static const MobCatEntry kMobCatTable[] = {"
)
foreach ($e in $sorted) {
    $lines += "    { 0x$($e.Key.ToUpper()), `"$($e.Value.xmid)`" },"
}
$lines += @(
    "};",
    "",
    "static const int kMobCatTableCount = (int)(sizeof(kMobCatTable) / sizeof(kMobCatTable[0]));",
    "",
    "// Returns the XMID string for an OG Xbox title ID, or NULL if unknown.",
    "static const char *MobCatXmidForTitleId(unsigned long titleId)",
    "{",
    "    int lo = 0, hi = kMobCatTableCount - 1;",
    "    while (lo <= hi)",
    "    {",
    "        const int mid = (lo + hi) / 2;",
    "        if      (kMobCatTable[mid].titleId < titleId) lo = mid + 1;",
    "        else if (kMobCatTable[mid].titleId > titleId) hi = mid - 1;",
    "        else return kMobCatTable[mid].xmid;",
    "    }",
    "    return NULL;",
    "}",
    "",
    "#endif"
)

$out = $lines -join "`n"
$dest = Join-Path (Split-Path $PSScriptRoot) "src\MobCatTable.h"
[System.IO.File]::WriteAllText($dest, $out)
Write-Host "Written $($sorted.Count) entries to $dest"