"""Generates FontData.h: the typefaces the UI writes out beside the XEX, as
byte arrays.

    python tools/make_font_data.py

  Selawik Bold      Media/Fonts/selawkb.ttf            bold, for the Xbox 360
                                                       theme (and as the fallback)
  Open Sans         Media/Fonts/OpenSans-Regular.ttf   the Series and Light themes
  Open Sans SemiBold Media/Fonts/OpenSans-SemiBold.ttf their bold: the Series
                                                       dashboard's weight
  Space Grotesk     Media/Fonts/SpaceGrotesk-Regular.ttf the Original Xbox theme:
                                                       not the dashboard's own
                                                       type, but as futuristic
  Space Grotesk Bold Media/Fonts/SpaceGrotesk-Bold.ttf its bold

Selawik Regular is not here: it travels as the XEX's "selawk" section (see
AdditionalSections in XboxTLS2.vcxproj). The others can't, because a fourth
XEX section stopped the XEX reaching main() on hardware - not a line logged -
and taking it out fixed it. So they're compiled in as data, the way the button
art is, and UiText.cpp writes each out to a file beside the XEX for XUI to
load.

Every font is copied byte for byte, so each is still itself under the SIL Open
Font License; Media/Fonts/OFL.txt carries both copyright notices and the
licence, and travels in the XEX as the "ofl" section.
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, 'src', 'FontData.h')

FONTS = [
    ('kSelawikBoldTtf', 'selawkb.ttf', 'Selawik Bold'),
    ('kOpenSansTtf', 'OpenSans-Regular.ttf', 'Open Sans Regular'),
    ('kOpenSansSemiBoldTtf', 'OpenSans-SemiBold.ttf', 'Open Sans SemiBold'),
    ('kSpaceGroteskTtf', 'SpaceGrotesk-Regular.ttf', 'Space Grotesk Regular'),
    ('kSpaceGroteskBoldTtf', 'SpaceGrotesk-Bold.ttf', 'Space Grotesk Bold'),
]

lines = [
    '// GENERATED by tools/make_font_data.py - do not edit by hand; re-run the',
    '// script. TrueType files from Media/Fonts (SIL Open Font License), byte for',
    '// byte. See the script for why they are compiled in.',
    '',
    '#ifndef FONT_DATA_H',
    '#define FONT_DATA_H',
    '',
]
for symbol, name, title in FONTS:
    data = open(os.path.join(ROOT, 'Media', 'Fonts', name), 'rb').read()
    lines += [
        '// %s, Media/Fonts/%s' % (title, name),
        'static const unsigned long %sSize = %d;' % (symbol, len(data)),
        'static const unsigned char %s[%d] =' % (symbol, len(data)),
        '{',
    ]
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    lines += ['};', '']
lines += ['#endif', '']

open(OUTPUT, 'w', newline='\r\n').write('\n'.join(lines))
print('wrote %s' % os.path.relpath(OUTPUT, ROOT))
