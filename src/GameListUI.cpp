// Milliseconds on the high-resolution counter, for timing the image work done
// on this thread - covers and Store art are decoded on their workers, but
// copied into textures here, between frames, so what that costs is a stall in
// drawing. Anything at or over IMAGE_TIMING_LOG_MS is logged with "[timing]".
#define IMAGE_TIMING_LOG_MS 4.0

static double TimerMs()
{
    static double msPerTick = 0.0;
    if (msPerTick == 0.0)
    {
        LARGE_INTEGER frequency;
        QueryPerformanceFrequency(&frequency);
        msPerTick = 1000.0 / (double)frequency.QuadPart;
    }
    LARGE_INTEGER now;
    QueryPerformanceCounter(&now);
    return (double)now.QuadPart * msPerTick;
}

