// Asks for the Store covers of the games on screen that don't have one yet,
// if that list has changed since last asked.
static unsigned long g_storeCoversAsked[MAX_STORE_COVERS];
static int g_storeCoversAskedCount = -1; // -1: ask again whatever's on screen

static void RequestMissingStoreCovers(const unsigned long *want, int wantCount)
{
    unsigned long *asked = g_storeCoversAsked;
    int &askedCount = g_storeCoversAskedCount;

    bool same = (wantCount == askedCount);
    for (int i = 0; same && i < wantCount; ++i)
        same = (want[i] == asked[i]);
    if (same)
        return;

    memcpy(asked, want, wantCount * sizeof(want[0]));
    askedCount = wantCount;
    RequestStoreCoverArt(want, wantCount);
}

// The covers of `rows` rows of a letter from firstRow.
static void RequestVisibleStoreCovers(const StoreLetterView &view, int firstRow, int rows, int cols)
{
    unsigned long want[MAX_STORE_COVERS];
    int wantCount = 0;
    for (int item = firstRow * cols; item < (firstRow + rows) * cols && item < view.count; ++item)
    {
        const unsigned long tid = view.tiles[item].titleId;
        if (tid != 0 && StoreCoverFor(tid) == NULL && wantCount < MAX_STORE_COVERS)
            want[wantCount++] = tid;
    }
    RequestMissingStoreCovers(want, wantCount);
}

