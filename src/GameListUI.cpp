static bool IsBetaBuild()
{
    return strstr(CURRENT_VERSION, "-beta") != NULL;
}

// The BETA badge after the app's name: a green pill raised like a
// superscript, its middle level with the top of "360" - the startup screen's
// pill, shaped the same (twice its label's capitals tall), but with the label
// kept at the smallest size the UI uses anywhere, so it can still be read.
struct BetaBadge
{
    float x, centerY, w, h;
};

#define BETA_LABEL_SIZE 0.56f

static BetaBadge LayOutBetaBadge()
{
    // Measured once: the sidebar draws this every frame.
    static float nameEm = 0.0f, labelEm = 0.0f, nameW = 0.0f, labelW = 0.0f;
    if (nameEm == 0.0f)
    {
        nameEm = BoldEm(1.1f);
        labelEm = BoldEm(BETA_LABEL_SIZE);
        nameW = TextWidth("Omni360", 1.1f, true);
        labelW = TextWidth("BETA", BETA_LABEL_SIZE, true);
    }

    BetaBadge b;
    const float nameTop = g_M.headerY + S(4.0f);
    const float capMid = nameTop + LineHeight(1.1f) * (0.5f + TEXT_CAP_DROP);
    b.h = SELAWIK_CAP / SELAWIK_EM * labelEm * 2.0f;
    b.w = labelW + b.h * 0.9f;
    b.x = g_M.safeX + nameW + nameEm * 0.07f;
    b.centerY = capMid - (SELAWIK_DIGIT_TOP - SELAWIK_CAP * 0.5f) / SELAWIK_EM * nameEm;
    return b;
}

