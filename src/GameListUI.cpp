static bool NavShown(int page)
{
    return !g_sidebar.hidden[page];
}

// Where each shown page's button starts, the hidden ones taking no room. The
// divider sits in the gap before Queue, splitting the things you browse from
// the things you manage. With every page shown they sit a little closer, so
// the last stays clear of the storage ring on a 480p screen.
static float NavItemY(int page)
{
    int shown = 0, before = 0;
    for (int p = 0; p < SHELL_PAGE_COUNT; ++p)
    {
        if (!NavShown(p))
            continue;
        if (p < page)
            before++;
        shown++;
    }
    float y = g_M.listY + before * S(shown > 6 ? 58.0f : 62.0f);
    if (page >= SHELL_PAGE_QUEUE)
        y += S(26.0f);
    return y;
}

static float NavRight()
{
    return g_M.navX + g_M.navW - S(18.0f);
}

// The count beside a page's name, and its pill: grey for the library, green
// for downloads still to do.
struct NavCount
{
    char text[16];
    float w, h;
};

static bool NavCountFor(int page, NavCount *out)
{
    int count = 0;
    if (page == SHELL_PAGE_LIBRARY) count = g_sidebar.libraryCount;
    if (page == SHELL_PAGE_APPS) count = g_sidebar.appsCount;
    if (page == SHELL_PAGE_HOMEBREW) count = g_sidebar.homebrewCount;
    if (page == SHELL_PAGE_EMULATORS) count = g_sidebar.emulatorsCount;
    if (page == SHELL_PAGE_QUEUE) count = g_sidebar.queueCount;
    if (count <= 0)
        return false;

    _snprintf(out->text, sizeof(out->text), "%d", count);
    out->text[sizeof(out->text) - 1] = '\0';

    out->h = S(26.0f);
    out->w = TextWidth(out->text, 0.68f, true) + S(16.0f);
    if (out->w < S(30.0f)) out->w = S(30.0f);
    return true;
}

// Selawik Bold, in its units: 2048 to the em. The O's outline and its hole -
// thick sides, thin top and bottom - its advance, and the digits' height.
// Read from Media/Fonts/selawkb.ttf.
#define SELAWIK_EM        2048.0f
#define SELAWIK_O_ADVANCE 1553.0f
#define SELAWIK_O_CX       777.0f // from the pen
#define SELAWIK_O_CY       716.0f // above the baseline; the capitals' middle is 717
#define SELAWIK_O_RX       703.0f // the outline's half-width, and half-height
#define SELAWIK_O_RY       741.0f
#define SELAWIK_O_IRX      367.0f // the hole's
#define SELAWIK_O_IRY      470.5f
#define SELAWIK_O_RIGHT   1480.0f // the outline's right edge, from the pen
#define SELAWIK_DIGIT_TOP 1460.0f // the top of "3", above the baseline
#define SELAWIK_CAP       1434.0f

// Selawik Bold's em in pixels at a text size, measured rather than assumed:
// the width ten O's add over one is nine advances, whatever padding XUI puts
// around a string.
static float BoldEm(float mul)
{
    const float em = (TextWidth("OOOOOOOOOO", mul, true) - TextWidth("O", mul, true)) /
                     (9.0f * SELAWIK_O_ADVANCE / SELAWIK_EM);
    return em > 0.0f ? em : LineHeight(mul);
}

// The BETA badge after the app's name - here and on the startup screen - for
