// Both of StfsParser's decode paths produce real UTF-8, multi-byte sequences
// included, so this has to decode rather than widen. A byte-widen (one WCHAR
// per input byte, as this used to do) is only correct for single-byte UTF-8:
// any title with a genuine multi-byte character - confirmed on "Modern
// Warfare(R) 3", where U+00AE is encoded as 0xC2 0xAE - rendered as two
// garbled characters instead of one.
//
// BMP range is enough here. These are STFS display names, not
// supplementary-plane text, and the font would have nothing to draw for it
// anyway.
static void Utf8ToWide(const char *in, WCHAR *out, int outSize)
{
    const unsigned char *p = (const unsigned char *)in;
    int o = 0;

    while (*p != '\0' && o < outSize - 1)
    {
        unsigned char b0 = p[0];
        unsigned long cp;
        int extraBytes;

        if (b0 < 0x80)          { cp = b0;          extraBytes = 0; }
        else if ((b0 & 0xE0) == 0xC0) { cp = b0 & 0x1F; extraBytes = 1; }
        else if ((b0 & 0xF0) == 0xE0) { cp = b0 & 0x0F; extraBytes = 2; }
        else if ((b0 & 0xF8) == 0xF0) { cp = b0 & 0x07; extraBytes = 3; }
        else { p++; out[o++] = L'?'; continue; } // stray continuation/invalid lead byte

        const unsigned char *seq = p + 1;
        int i;
        for (i = 0; i < extraBytes; ++i)
        {
            if (seq[i] == '\0' || (seq[i] & 0xC0) != 0x80)
                break; // truncated/malformed sequence
            cp = (cp << 6) | (seq[i] & 0x3F);
        }

        if (i < extraBytes)
        {
            // malformed - emit '?' for the lead byte only, resync there
            out[o++] = L'?';
            p++;
            continue;
        }

        p += 1 + extraBytes;
        out[o++] = (cp <= 0xFFFF) ? (WCHAR)cp : L'?'; // outside BMP: not expected for a title name, and this font has no such glyphs anyway
    }

    out[o] = L'\0';
}

