struct ShapeStyle
{
    float radius;
    float stroke;       // > 0 draws only a band this wide inside the edge
    float blur;         // > 0 draws a soft shadow falling off over this many pixels
    bool ring;          // a ring instead of a box - see DrawRing
    float ringFraction;
    bool line;          // a line instead of a box - see DrawLine
    float lineAX, lineAY, lineBX, lineBY;
};

static ShapeStyle Shape(float radius)
{
    ShapeStyle s;
    s.radius = radius;
    s.stroke = 0.0f;
    s.blur = 0.0f;
    s.ring = false;
    s.ringFraction = 0.0f;
    s.line = false;
    s.lineAX = s.lineAY = s.lineBX = s.lineBY = 0.0f;
    return s;
}

// The shape at x,y,w,h, drawn on a quad grown by pad on every side - room for
// a shadow's falloff. Texture coordinates span the shape itself, so only use
// pad with an untextured shape.
//
// The state setup is DrawQuadUV's, line for line - that list is what took
// hardware debugging to get right, and the two draws must leave the device in
// the same condition.
static void DrawShape(D3DTexture *texture, float x, float y, float w, float h, float pad,
                      float u0, float v0, float u1, float v1,
                      D3DCOLOR tint, D3DCOLOR gradA, D3DCOLOR gradB, bool vertical,
                      const ShapeStyle &style)
{
    if (w <= 0.0f || h <= 0.0f)
        return;

    if (!g_shapesReady)
    {
        // Square, flat, no shadow: the UI without the shader. A stroke is
        // drawn as four bars so focus still shows; a ring or a line is left
        // out.
        if (style.blur > 0.0f || style.ring || style.line)
            return;
        if (style.stroke > 0.0f)
        {
            float t = style.stroke;
            DrawQuadUV(NULL, x, y, w, t, 0, 0, 1, 1, tint, gradA, gradB, vertical);
            DrawQuadUV(NULL, x, y + h - t, w, t, 0, 0, 1, 1, tint, gradA, gradB, vertical);
            DrawQuadUV(NULL, x, y + t, t, h - 2 * t, 0, 0, 1, 1, tint, gradA, gradB, vertical);
            DrawQuadUV(NULL, x + w - t, y + t, t, h - 2 * t, 0, 0, 1, 1, tint, gradA, gradB, vertical);
            return;
        }
        DrawQuadUV(texture, x, y, w, h, u0, v0, u1, v1, tint, gradA, gradB, vertical);
        return;
    }

    float tintF[4], gradAF[4], gradBF[4];
    ColorToFloat4(tint, tintF);
    ColorToFloat4(gradA, gradAF);
    ColorToFloat4(gradB, gradBF);

    float radius = style.radius;
    float maxRadius = (w < h ? w : h) * 0.5f;
    if (radius > maxRadius) radius = maxRadius;

    float axis[4] = {vertical ? 0.0f : 1.0f, vertical ? 1.0f : 0.0f, 0.0f, 0.0f};
    float rect[4] = {x, y, w, h};
    float params[4] = {radius, style.stroke, style.blur, style.line ? 2.0f : (style.ring ? 1.0f : 0.0f)};
    float ring[4] = {style.ringFraction, 0.0f, 0.0f, 0.0f};
    float line[4] = {style.lineAX, style.lineAY, style.lineBX, style.lineBY};

    g_pd3dDevice->SetPixelShaderConstantF(1, tintF, 1);
    g_pd3dDevice->SetPixelShaderConstantF(2, gradAF, 1);
    g_pd3dDevice->SetPixelShaderConstantF(3, gradBF, 1);
    g_pd3dDevice->SetPixelShaderConstantF(4, axis, 1);
    g_pd3dDevice->SetPixelShaderConstantF(5, rect, 1);
    g_pd3dDevice->SetPixelShaderConstantF(6, params, 1);
    g_pd3dDevice->SetPixelShaderConstantF(7, ring, 1);
    g_pd3dDevice->SetPixelShaderConstantF(8, line, 1);

    g_pd3dDevice->SetTexture(0, texture != NULL ? texture : g_pWhiteTexture);
    g_pd3dDevice->SetVertexDeclaration(g_pQuadVertexDecl);
    g_pd3dDevice->SetVertexShader(g_pShapeVertexShader);
    g_pd3dDevice->SetPixelShader(g_pShapePixelShader);

    g_pd3dDevice->SetRenderState(D3DRS_ALPHABLENDENABLE, TRUE);
    g_pd3dDevice->SetRenderState(D3DRS_SRCBLEND, D3DBLEND_SRCALPHA);
    g_pd3dDevice->SetRenderState(D3DRS_DESTBLEND, D3DBLEND_INVSRCALPHA);
    g_pd3dDevice->SetRenderState(D3DRS_BLENDOP, D3DBLENDOP_ADD);
    g_pd3dDevice->SetRenderState(D3DRS_ALPHATESTENABLE, FALSE);
    g_pd3dDevice->SetRenderState(D3DRS_FILLMODE, D3DFILL_SOLID);
    g_pd3dDevice->SetRenderState(D3DRS_CULLMODE, D3DCULL_NONE);
    g_pd3dDevice->SetRenderState(D3DRS_ZENABLE, FALSE);
    g_pd3dDevice->SetRenderState(D3DRS_STENCILENABLE, FALSE);
    g_pd3dDevice->SetRenderState(D3DRS_VIEWPORTENABLE, FALSE);
    g_pd3dDevice->SetRenderState(D3DRS_COLORWRITEENABLE, 0x0000000F);
    ApplyClip();
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_MINFILTER, D3DTEXF_LINEAR);
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_MAGFILTER, D3DTEXF_LINEAR);
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_MIPFILTER, D3DTEXF_NONE);
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_ADDRESSU, D3DTADDRESS_CLAMP);
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_ADDRESSV, D3DTADDRESS_CLAMP);

    const float qx = x - pad, qy = y - pad, qw = w + pad * 2.0f, qh = h + pad * 2.0f;

    volatile FLOAT *pVertex;
    if (SUCCEEDED(g_pd3dDevice->BeginVertices(D3DPT_QUADLIST, 4, sizeof(QuadVertex), (VOID **)&pVertex)))
    {
        pVertex[0] = qx;        pVertex[1] = qy;        pVertex[2] = u0;  pVertex[3] = v0;  // TL
        pVertex[4] = qx + qw;   pVertex[5] = qy;        pVertex[6] = u1;  pVertex[7] = v0;  // TR
        pVertex[8] = qx + qw;   pVertex[9] = qy + qh;   pVertex[10] = u1; pVertex[11] = v1; // BR
        pVertex[12] = qx;       pVertex[13] = qy + qh;  pVertex[14] = u0; pVertex[15] = v1; // BL

        g_pd3dDevice->EndVertices();
    }

    g_pd3dDevice->SetTexture(0, NULL);
    g_pd3dDevice->SetVertexDeclaration(NULL);
    g_pd3dDevice->SetVertexShader(NULL);
    g_pd3dDevice->SetPixelShader(NULL);
}

static void FillRound(float x, float y, float w, float h, float radius, D3DCOLOR color)
{
    DrawShape(NULL, x, y, w, h, 0.0f, 0, 0, 1, 1, color, 0xFFFFFFFF, 0xFFFFFFFF, true, Shape(radius));
}

static void FillRoundGradient(float x, float y, float w, float h, float radius,
                              D3DCOLOR colorA, D3DCOLOR colorB, bool vertical)
{
    DrawShape(NULL, x, y, w, h, 0.0f, 0, 0, 1, 1, 0xFFFFFFFF, colorA, colorB, vertical, Shape(radius));
}

// A band of `width` just inside the edge of x,y,w,h.
static void StrokeRound(float x, float y, float w, float h, float radius, float width, D3DCOLOR color)
{
    ShapeStyle s = Shape(radius);
    s.stroke = width;
    DrawShape(NULL, x, y, w, h, 0.0f, 0, 0, 1, 1, color, 0xFFFFFFFF, 0xFFFFFFFF, true, s);
}

// A shadow the shape of x,y,w,h, fading out over `blur` beyond its edge.
static void ShadowRound(float x, float y, float w, float h, float radius, float blur, D3DCOLOR color)
{
    ShapeStyle s = Shape(radius);
    s.blur = blur;
    DrawShape(NULL, x, y, w, h, blur, 0, 0, 1, 1, color, 0xFFFFFFFF, 0xFFFFFFFF, true, s);
}

// A texture, or the part of it u0..v1, with rounded corners. gradA/gradB
// multiply it, top to bottom - white for the texture as it is.
static void TextureRound(D3DTexture *texture, float x, float y, float w, float h, float radius,
                         float u0, float v0, float u1, float v1, D3DCOLOR gradA, D3DCOLOR gradB)
{
    DrawShape(texture, x, y, w, h, 0.0f, u0, v0, u1, v1, 0xFFFFFFFF, gradA, gradB, true, Shape(radius));
}

// A ring centred on cx,cy: `used` for `fraction` of a turn clockwise from the
// top, `track` for the rest.
static void DrawRing(float cx, float cy, float outerRadius, float thickness, float fraction,
                     D3DCOLOR used, D3DCOLOR track)
{
    ShapeStyle s = Shape(0.0f);
    s.ring = true;
    s.stroke = thickness;
    s.ringFraction = fraction;
    DrawShape(NULL, cx - outerRadius, cy - outerRadius, outerRadius * 2.0f, outerRadius * 2.0f, 0.0f,
              0, 0, 1, 1, used, track, track, true, s);
}

// A line from (ax, ay) to (bx, by), `thickness` wide, with round ends. The
// quad is the line's bounding box, grown to take its ends.
static void DrawLine(float ax, float ay, float bx, float by, float thickness, D3DCOLOR color)
{
    ShapeStyle s = Shape(0.0f);
    s.line = true;
    s.stroke = thickness;
    s.lineAX = ax;
    s.lineAY = ay;
    s.lineBX = bx;
    s.lineBY = by;

    const float grow = thickness * 0.5f + 1.0f;
    const float x0 = (ax < bx ? ax : bx) - grow, x1 = (ax > bx ? ax : bx) + grow;
    const float y0 = (ay < by ? ay : by) - grow, y1 = (ay > by ? ay : by) + grow;
    DrawShape(NULL, x0, y0, x1 - x0, y1 - y0, 0.0f, 0, 0, 1, 1, color, 0xFFFFFFFF, 0xFFFFFFFF, true, s);
}

// A tick, centred on cx,cy, sized for a disc of diameter d: a short stroke
// down to the right, then a long one up.
static void DrawTick(float cx, float cy, float d, D3DCOLOR color)
{
    const float thickness = d * 0.11f;
    const float ax = cx - d * 0.22f, ay = cy + d * 0.01f;
    const float bx = cx - d * 0.06f, by = cy + d * 0.17f;
    const float tx = cx + d * 0.23f, ty = cy - d * 0.15f;
    DrawLine(ax, ay, bx, by, thickness, color);
    DrawLine(bx, by, tx, ty, thickness, color);
}

// The focus ring: white, a little outside the thing focused, its corners
// following the thing's own.
static void FocusRing(float x, float y, float w, float h, float radius)
{
    const float t = S(3.0f), gap = S(3.0f), out = t + gap;
    StrokeRound(x - out, y - out, w + out * 2.0f, h + out * 2.0f, radius > 0.0f ? radius + out : 0.0f, t, COL_FOCUS);
}

// ---------------------------------------------------------------------------
// Text
// ---------------------------------------------------------------------------
//
// One call per string: size as a multiple of the design height, weight, and
// UTF-8 in. Every page draws all of its text through these, inside the one
// font Begin/End the frame has.

static float LineHeight(float mul)
{
    return 22.0f * g_M.textScale * mul;
}

// How far below the middle of a line's nominal height the middle of its
// capitals sits, as a fraction of that height. Selawik's ascent and XUI's
// leading put the glyphs low in the box: on a 1080p capture the sidebar's
// "Your Library" had its capitals centred 2.5px below its button's centre,
// at a nominal 31px. Centring the capitals is what reads as centred - the
// usual rule for buttons - and keeps digits in pills centred too.
#define TEXT_CAP_DROP 0.08f

// DrawText positions text by its top edge, so centring on a line means
// subtracting half the line height - and the capitals' drop below its middle.
static float TextTopForCenter(float centerY, float yScale)
{
    const float height = g_UiFont.GetFontHeight() * yScale;
    return centerY - height * (0.5f + TEXT_CAP_DROP);
}

static void SetType(float mul, bool bold)
{
    g_UiFont.SetBold(bold);
    g_UiFont.SetScaleFactors(mul * g_M.textScale, mul * g_M.textScale);
}

static void Text(float x, float y, float mul, D3DCOLOR color, const char *utf8,
                 DWORD flags = 0, float maxW = 0.0f, bool bold = false)
{
    if (utf8 == NULL || utf8[0] == '\0')
        return;

    WCHAR wide[256];
    Utf8ToWide(utf8, wide, 256);

    SetType(mul, bold);
    g_UiFont.DrawText(x, y, color, wide, flags, maxW);
}

// Truncated to maxW when maxW > 0.
static void TextFit(float x, float y, float mul, D3DCOLOR color, const char *utf8, float maxW, bool bold = false)
{
    Text(x, y, mul, color, utf8, maxW > 0.0f ? ATGFONT_TRUNCATED : 0, maxW, bold);
}

static void TextMid(float x, float centerY, float mul, D3DCOLOR color, const char *utf8,
                    DWORD flags = 0, float maxW = 0.0f, bool bold = false)
{
    Text(x, TextTopForCenter(centerY, mul * g_M.textScale), mul, color, utf8, flags, maxW, bold);
}

static float TextWidth(const char *utf8, float mul, bool bold = false)
{
    if (utf8 == NULL || utf8[0] == '\0')
        return 0.0f;

    WCHAR wide[256];
    Utf8ToWide(utf8, wide, 256);

    SetType(mul, bold);
    return g_UiFont.GetTextWidth(wide);
}

// A focused tile's name that's too long for it scrolls, as on the Xbox
// dashboard: a pause, a slow scroll to its end, a pause, and a fade back to
// the start. XUI's text can't be cut to a rectangle (see g_clipOn), so the
// characters are drawn one by one: each fades as it nears the left edge and
// is gone by the time it would cross it, and the next ones fade in at the
// right. They run up to MARQUEE_BLEED into the padding callers leave either
// side - never past the tile.
#define MARQUEE_HOLD_MS    1500
#define MARQUEE_FADE_MS    300   // the fade out and back in between scrolls
#define MARQUEE_SPEED      45.0f // design pixels a second
#define MARQUEE_BLEED      12.0f // design pixels; callers leave 14
#define MARQUEE_EDGE       24.0f // design pixels a character takes to fade
#define MARQUEE_MAX_CHARS  127

static struct
{
    const char *text; // what's measured below: another name starts over
    float mul;
    bool bold;
    DWORD startedAt;
    DWORD drawnAt;    // a frame without it - another page - starts over too
    int count;        // characters in wide
    WCHAR wide[MARQUEE_MAX_CHARS + 1];
    unsigned char len[MARQUEE_MAX_CHARS];  // each character's WCHARs: 2 for a surrogate pair
    float left[MARQUEE_MAX_CHARS];         // each one's edges; a space's aren't kept
    float right[MARQUEE_MAX_CHARS];
    float width;                           // all of it
} g_marquee;

static float Clamp01(float v)
{
    return v < 0.0f ? 0.0f : (v > 1.0f ? 1.0f : v);
}

static D3DCOLOR WithAlpha(D3DCOLOR color, float alpha)
{
    const float a = (float)(color >> 24) * alpha;
    return ((D3DCOLOR)(a + 0.5f) << 24) | (color & 0x00FFFFFF);
}

// The text's characters and where each starts, measured once a name.
static void MeasureMarquee(const char *utf8, float mul, bool bold)
{
    g_marquee.text = utf8;
    g_marquee.mul = mul;
    g_marquee.bold = bold;

    WCHAR wide[MARQUEE_MAX_CHARS + 1];
    Utf8ToWide(utf8, wide, MARQUEE_MAX_CHARS + 1);
    SetType(mul, bold);

    int n = 0;
    int at = 0;
    while (wide[at] != L'\0')
    {
        const int len = (wide[at] >= 0xD800 && wide[at] <= 0xDBFF && wide[at + 1] != L'\0') ? 2 : 1;
        // Its right edge is the width of everything up to and including it,
        // so kerning and rounding don't add up character by character, and
        // its left that less its own. Not the width of what's before it:
        // XuiMeasureText leaves out trailing spaces, so a word after a space
        // would start where the space does.
        if (wide[at] != L' ')
        {
            memcpy(g_marquee.wide, wide, (at + len) * sizeof(WCHAR));
            g_marquee.wide[at + len] = L'\0';
            g_marquee.right[n] = g_UiFont.GetTextWidth(g_marquee.wide);
            g_marquee.left[n] = g_marquee.right[n] - g_UiFont.GetTextWidth(g_marquee.wide + at);
        }
        g_marquee.len[n++] = (unsigned char)len;
        at += len;
    }
    memcpy(g_marquee.wide, wide, (at + 1) * sizeof(WCHAR));
    g_marquee.width = g_UiFont.GetTextWidth(g_marquee.wide);
    g_marquee.count = n;
}

// As TextMid with ATGFONT_TRUNCATED, for the focused tile's name: one that
// fits is drawn as it is, a longer one scrolls.
static void MarqueeTextMid(float x, float centerY, float mul, D3DCOLOR color, const char *utf8, float maxW,
                           bool bold)
{
    if (utf8 == NULL || utf8[0] == '\0')
        return;

    const DWORD now = GetTickCount();
    if (g_marquee.text != utf8 || g_marquee.mul != mul || g_marquee.bold != bold || now - g_marquee.drawnAt > 250)
    {
        MeasureMarquee(utf8, mul, bold);
        g_marquee.startedAt = now;
    }
    g_marquee.drawnAt = now;

    const float full = g_marquee.width;
    if (full <= maxW)
    {
        TextMid(x, centerY, mul, color, utf8, ATGFONT_TRUNCATED, maxW, bold);
        return;
    }

    // Where the scroll is: holding at the start, moving, holding at the end,
    // then fading out to start again - fading in, after the first time.
    const float travel = full - maxW;
    const float speed = S(MARQUEE_SPEED);
    const DWORD scrollMs = (DWORD)(travel / speed * 1000.0f);
    const DWORD cycle = MARQUEE_HOLD_MS + scrollMs + MARQUEE_HOLD_MS + MARQUEE_FADE_MS;
    const DWORD elapsed = now - g_marquee.startedAt;
    const DWORD t = elapsed % cycle;

    float offset = 0.0f;
    if (t > MARQUEE_HOLD_MS)
        offset = (t - MARQUEE_HOLD_MS) * speed / 1000.0f;
    if (offset > travel)
        offset = travel;

    float fade = 1.0f;
    if (t >= cycle - MARQUEE_FADE_MS)
        fade = (float)(cycle - t) / MARQUEE_FADE_MS;
    else if (elapsed >= cycle && t < MARQUEE_FADE_MS)
        fade = (float)t / MARQUEE_FADE_MS;

    // The edges' fades come in as the text moves away from them, so the
    // first character is whole until it starts to go and the last whole once
    // it's arrived.
    const float bleed = S(MARQUEE_BLEED);
    const float edge = S(MARQUEE_EDGE);
    const float leftEdge = x - bleed;
    const float rightEdge = x + maxW + bleed;
    const float leftOn = Clamp01(offset / bleed);
    const float rightOn = Clamp01((travel - offset) / bleed);

    const float top = TextTopForCenter(centerY, mul * g_M.textScale);
    SetType(mul, bold);

    WCHAR one[3];
    int at = 0;
    for (int i = 0; i < g_marquee.count; at += g_marquee.len[i], ++i)
    {
        if (g_marquee.wide[at] == L' ')
            continue;
        const float cx = x + g_marquee.left[i] - offset;
        const float cr = x + g_marquee.right[i] - offset;
        if (cx < leftEdge || cr > rightEdge)
            continue;

        float alpha = fade;
        alpha *= 1.0f - leftOn * (1.0f - Clamp01((cx - leftEdge) / edge));
        alpha *= 1.0f - rightOn * (1.0f - Clamp01((rightEdge - cr) / edge));
        if (alpha <= 0.0f)
            continue;

        one[0] = g_marquee.wide[at];
        one[1] = (g_marquee.len[i] == 2) ? g_marquee.wide[at + 1] : L'\0';
        one[2] = L'\0';
        g_UiFont.DrawText(cx, top, WithAlpha(color, alpha), one, 0, 0.0f);
    }
}

// Wrapped text: XUI's own wrapping is off (UiText draws single lines), so
// lines are broken here, at spaces and at '\n', by measuring. A paragraph
// is measured once and its breaks remembered, since the same few are drawn
// every frame - a Store description is a few hundred characters.
#define WRAP_MAX_LINES  16
#define WRAP_CACHE_SIZE 12

struct WrapLayout
{
    unsigned long key;
    int count;
    unsigned short start[WRAP_MAX_LINES];
    unsigned short len[WRAP_MAX_LINES];
    bool more; // text was left over: the last line takes the rest, with an ellipsis
};

static WrapLayout g_wrapCache[WRAP_CACHE_SIZE];
static int g_wrapNext = 0;

static unsigned long WrapKey(const char *utf8, float maxW, float mul, bool bold, int maxLines)
{
    unsigned long h = 2166136261UL;
    for (const unsigned char *p = (const unsigned char *)utf8; *p; ++p)
        h = (h ^ *p) * 16777619UL;
    h = (h ^ (unsigned long)(maxW * 4.0f)) * 16777619UL;
    h = (h ^ (unsigned long)(mul * 1000.0f)) * 16777619UL;
    h = (h ^ (unsigned long)(maxLines * 2 + (bold ? 1 : 0))) * 16777619UL;
    return h != 0 ? h : 1;
}

static float SpanWidth(const char *utf8, int start, int len, float mul, bool bold)
{
    char span[256];
    if (len > (int)sizeof(span) - 1)
        len = (int)sizeof(span) - 1;
    memcpy(span, utf8 + start, len);
    span[len] = '\0';
    return TextWidth(span, mul, bold);
}

static const WrapLayout &LayOutWrap(const char *utf8, float maxW, float mul, bool bold, int maxLines)
{
    if (maxLines > WRAP_MAX_LINES)
        maxLines = WRAP_MAX_LINES;
    const unsigned long key = WrapKey(utf8, maxW, mul, bold, maxLines);
    for (int i = 0; i < WRAP_CACHE_SIZE; ++i)
    {
        if (g_wrapCache[i].key == key)
            return g_wrapCache[i];
    }

    WrapLayout &w = g_wrapCache[g_wrapNext];
    g_wrapNext = (g_wrapNext + 1) % WRAP_CACHE_SIZE;
    memset(&w, 0, sizeof(w));
    w.key = key;

    const int n = (int)strlen(utf8);
    int pos = 0;
    while (pos < n && w.count < maxLines)
    {
        while (pos < n && (utf8[pos] == ' ' || utf8[pos] == '\r'))
            pos++;
        if (pos >= n)
            break;
        if (utf8[pos] == '\n')
        {
            // A blank line, between paragraphs.
            w.start[w.count] = (unsigned short)pos;
            w.len[w.count] = 0;
            w.count++;
            pos++;
            continue;
        }

        // Word by word while the line still fits. A word too long for a
        // line on its own still gets one, and is cut off there.
        int end = pos;
        bool hardBreak = false;
        for (;;)
        {
            int next = end;
            while (next < n && (utf8[next] == ' ' || utf8[next] == '\r'))
                next++;
            while (next < n && utf8[next] != ' ' && utf8[next] != '\r' && utf8[next] != '\n')
                next++;
            if (next == end)
                break;
            if (end > pos && (next - pos > 255 || SpanWidth(utf8, pos, next - pos, mul, bold) > maxW))
                break;
            end = next;
            if (end < n && utf8[end] == '\n')
            {
                hardBreak = true;
                break;
            }
        }

        // The last line allowed, with text still to come: it takes the rest,
        // and drawing truncates it with an ellipsis.
        bool last = (w.count == maxLines - 1);
        int rest = end;
        while (rest < n && (utf8[rest] == ' ' || utf8[rest] == '\r' || utf8[rest] == '\n'))
            rest++;
        if (last && rest < n)
        {
            int take = n - pos;
            if (take > 255)
                take = 255;
            w.start[w.count] = (unsigned short)pos;
            w.len[w.count] = (unsigned short)take;
            w.count++;
            w.more = true;
            break;
        }

        w.start[w.count] = (unsigned short)pos;
        w.len[w.count] = (unsigned short)(end - pos > 255 ? 255 : end - pos);
        w.count++;
        pos = hardBreak ? end + 1 : end;
    }
    return w;
}

// Draws utf8 wrapped to maxW, one line every lineH pixels from y, in at
// most maxLines lines. Returns the lines used. Only the first 64KB of a
// string is laid out.
static int TextWrapped(float x, float y, float mul, D3DCOLOR color, const char *utf8, float maxW,
                       float lineH, int maxLines, bool bold = false)
{
    if (utf8 == NULL || utf8[0] == '\0' || maxLines <= 0 || strlen(utf8) > 65535)
        return 0;

    const WrapLayout &w = LayOutWrap(utf8, maxW, mul, bold, maxLines);
    for (int i = 0; i < w.count; ++i)
    {
        char line[256];
        memcpy(line, utf8 + w.start[i], w.len[i]);
        line[w.len[i]] = '\0';
        bool truncate = (w.more && i == w.count - 1);
        Text(x, y + lineH * i, mul, color, line, truncate ? ATGFONT_TRUNCATED : 0, truncate ? maxW : 0.0f, bold);
    }
    return w.count;
}

// How many lines TextWrapped would use, for laying out what comes after.
static int TextWrappedLines(const char *utf8, float maxW, float mul, int maxLines, bool bold = false)
{
    if (utf8 == NULL || utf8[0] == '\0' || maxLines <= 0 || strlen(utf8) > 65535)
        return 0;
    return LayOutWrap(utf8, maxW, mul, bold, maxLines).count;
}

// ---------------------------------------------------------------------------
// Footer button hints
// ---------------------------------------------------------------------------
//
// The controller-button hints at the bottom right: the button's icon, then
// what it does. The icons are pre-rendered art from ButtonAtlas.h, one
// textured quad each; tools/make_button_atlas.py says how they are made.

// One hint. Laid out once and then drawn twice - the icon in the quad pass
// and the label in the font pass - so both read positions from here.
struct ButtonHint
{
    int          sprite; // BUTTON_SPRITE_*
    const WCHAR *label;

    float badgeX;
    float badgeW;
    float labelX;
};

#define HINT_LABEL_SCALE 0.78f

// A face button's on-screen diameter. Every sprite scales by the same factor,
// so the shoulder buttons keep their size relative to the face buttons.
static float HintBadgeHeight()
{
    return S(26.0f);
}

static float HintSpriteScale()
{
    return HintBadgeHeight() / (float)BUTTON_ATLAS_FACE_D;
}

// Walks the hints left to right from startX, measuring each label. Returns
// the total width.
static float LayoutButtonHints(ButtonHint *hints, int count, float startX)
{
    float k = HintSpriteScale();
    float gapBadgeToLabel = S(8.0f);
    float gapBetweenHints = S(28.0f);

    g_UiFont.SetBold(false);
    g_UiFont.SetScaleFactors(HINT_LABEL_SCALE * g_M.textScale, HINT_LABEL_SCALE * g_M.textScale);

    float x = startX;

    for (int i = 0; i < count; ++i)
    {
        hints[i].badgeX = x;
        hints[i].badgeW = (float)kButtonSprites[hints[i].sprite].boxW * k;
        hints[i].labelX = x + hints[i].badgeW + gapBadgeToLabel;

        x = hints[i].labelX + g_UiFont.GetTextWidth(hints[i].label) + gapBetweenHints;
    }

    return (count > 0) ? x - gapBetweenHints - startX : 0.0f;
}

// Right-aligned to the page's edge, as on the dashboard.
static void LayoutButtonHintsRight(ButtonHint *hints, int count)
{
    float width = LayoutButtonHints(hints, count, g_M.contentX);
    LayoutButtonHints(hints, count, g_M.contentX + g_M.contentW - width);
}

// One button icon, its left edge at boxX and centred vertically on centerY.
// Returns the on-screen width of the button itself (not its shadow).
static float DrawButtonSprite(int sprite, float boxX, float centerY)
{
    const float k = HintSpriteScale();
    const float invW = 1.0f / (float)BUTTON_ATLAS_WIDTH;
    const float invH = 1.0f / (float)BUTTON_ATLAS_HEIGHT;

    const ButtonSprite &s = kButtonSprites[sprite];

    // Position the button's own box, then draw the whole cell around it. The
    // margin between box and cell is the drop shadow, which is meant to fall
    // outside.
    float cellX = boxX - (float)s.boxX * k;
    float cellY = centerY - (float)s.boxH * k * 0.5f - (float)s.boxY * k;

    DrawQuadUV(g_pButtonAtlas, cellX, cellY, (float)s.cellW * k, (float)s.cellH * k,
               (float)s.cellX * invW, (float)s.cellY * invH,
               (float)(s.cellX + s.cellW) * invW, (float)(s.cellY + s.cellH) * invH,
               0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, true);

    return (float)s.boxW * k;
}

static void DrawButtonHintShapes(const ButtonHint *hints, int count, float centerY)
{
    for (int i = 0; i < count; ++i)
        DrawButtonSprite(hints[i].sprite, hints[i].badgeX, centerY);
}

// Must be called inside an open Font Begin/End.
static void DrawButtonHintText(const ButtonHint *hints, int count, float centerY)
{
    float labelScale = HINT_LABEL_SCALE * g_M.textScale;
    g_UiFont.SetBold(false);
    g_UiFont.SetScaleFactors(labelScale, labelScale);

    for (int i = 0; i < count; ++i)
    {
        g_UiFont.DrawText(hints[i].labelX, TextTopForCenter(centerY, labelScale),
                          COL_TEXT2, hints[i].label);
    }
}

// Full-screen wash, drawn first every frame: lightest at the top, settling to
// the background colour seven tenths of the way down.
