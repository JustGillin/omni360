#define TOAST_DURATION_MS 5000

struct ShellToast
{
    bool shown;
    DWORD shownAt;
    UiToastTone tone;
    char heading[64];
    char message[192];
};

static ShellToast g_toast = {false, 0, UI_TOAST_INFO, "", ""};

void ShowShellToast(const char *heading, const char *message, UiToastTone tone)
{
    g_toast.shown = true;
    g_toast.shownAt = GetTickCount();
    g_toast.tone = tone;
    strncpy(g_toast.heading, heading != NULL ? heading : "", sizeof(g_toast.heading) - 1);
    g_toast.heading[sizeof(g_toast.heading) - 1] = '\0';
    strncpy(g_toast.message, message != NULL ? message : "", sizeof(g_toast.message) - 1);
    g_toast.message[sizeof(g_toast.message) - 1] = '\0';
}

// Asked once per frame, so both passes agree on whether it's there. Elapsed
// time rather than an end time, which keeps the comparison right across
// GetTickCount wrapping.
static bool ToastVisibleThisFrame()
{
    if (g_toast.shown && GetTickCount() - g_toast.shownAt >= TOAST_DURATION_MS)
        g_toast.shown = false;
    return g_toast.shown;
}

struct ToastRect
{
    float x, y, w, h;
    float iconD, iconX, iconCY;
};

static ToastRect ToastLayout()
{
    ToastRect r;
    r.w = S(520.0f);
    if (r.w > g_M.contentW * 0.55f)
        r.w = g_M.contentW * 0.55f; // leaves the page title its room
    r.h = S(68.0f);
    r.x = g_M.contentX + g_M.contentW - r.w;
    r.y = g_M.headerY - S(6.0f);
    r.iconD = S(34.0f);
    r.iconX = r.x + S(16.0f);
    r.iconCY = r.y + r.h * 0.5f;
    return r;
}

static void DrawToastQuads()
{
    ToastRect r = ToastLayout();
    ShadowRound(r.x, r.y + S(6.0f), r.w, r.h, g_M.radius, S(18.0f), COL_SHADOW);
    FillRound(r.x, r.y, r.w, r.h, g_M.radius, COL_SURFACE_HI);

    D3DCOLOR iconColor = (g_toast.tone == UI_TOAST_ERROR) ? COL_ERROR
                       : (g_toast.tone == UI_TOAST_SUCCESS) ? COL_GREEN : COL_TRACK;
    FillRound(r.iconX, r.iconCY - r.iconD * 0.5f, r.iconD, r.iconD, r.iconD * 0.5f, iconColor);

    // Success is a white tick in the green disc - drawn, since the font has
    // none.
    if (g_toast.tone == UI_TOAST_SUCCESS)
        DrawTick(r.iconX + r.iconD * 0.5f, r.iconCY, r.iconD, COL_TEXT);
}

static void DrawToastText()
{
    ToastRect r = ToastLayout();

    if (g_toast.tone != UI_TOAST_SUCCESS)
        TextMid(r.iconX + r.iconD * 0.5f, r.iconCY, 0.8f, COL_TEXT,
                g_toast.tone == UI_TOAST_ERROR ? "!" : "i", ATGFONT_CENTER_X, 0.0f, true);

    const float textX = r.iconX + r.iconD + S(14.0f);
    const float textW = r.x + r.w - textX - S(16.0f);
    TextFit(textX, r.y + S(10.0f), 0.82f, COL_TEXT, g_toast.heading, textW, true);
    TextFit(textX, r.y + S(10.0f) + LineHeight(0.82f) * 1.2f + S(2.0f), 0.72f, COL_TEXT2, g_toast.message, textW);
}

