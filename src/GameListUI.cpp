// A game's tile at x,y, s across, cut off at h (less than s for the row that
// peeks out at the bottom of the grid). Its icon, drawn at about twice its
// 64px size, sits in the middle of a tile filled with the icon's own average
// colour - darker towards the bottom - so even a small icon fills the tile
// with something of the game's.
static void DrawTileArt(D3DTexture *boxArt, const Icon *icon, float x, float y, float s, float h)
{
    const float r = g_M.radius;

    // The box art fills the tile, cropped with it - fading in over the tile
    // it replaces, if it's only just arrived.
    if (boxArt != NULL)
    {
        const float fade = ArtFade(boxArt);
        if (fade < 1.0f)
            DrawTileArt(NULL, icon, x, y, s, h);
        const D3DCOLOR tint = WithAlpha(0xFFFFFFFF, fade);
        TextureRound(boxArt, x, y, s, h, r, 0.0f, 0.0f, 1.0f, h / s, tint, tint);
        return;
    }

    if (icon != NULL && icon->average != NULL)
        TextureRound(icon->average, x, y, s, h, r, 0.0f, 0.0f, 1.0f, 1.0f, 0xFFFFFFFF, 0xFF808080);
    else
        FillRoundGradient(x, y, s, h, r, COL_SURFACE_HI, COL_SURFACE, true);

    if (icon == NULL || icon->texture == NULL)
        return;

    float iw = s * 0.485f, ih = s * 0.485f;
    if (icon->aspect > 1.0f) ih = iw / icon->aspect;
    else if (icon->aspect < 1.0f) iw = ih * icon->aspect;

    const float ix = x + (s - iw) * 0.5f;
    const float iy = y + (s - ih) * 0.5f;

    // Cropped with the tile, by shortening its texture coordinates.
    float visibleH = (y + h) - iy;
    if (visibleH <= 0.0f)
        return;
    if (visibleH > ih)
        visibleH = ih;

    TextureRound(icon->texture, ix, iy, iw, visibleH, R(4.0f), 0.0f, 0.0f, 1.0f, visibleH / ih,
                 0xFFFFFFFF, 0xFFFFFFFF);
}

// A small square cover - the queue's. The icon fills it, over its average
// colour in case it has transparency.
// A cover over x,y,w,h, the texture's u running 0..u1 across it - past 1 only
// for DrawCoverFlushLeft, which clips the extra off.
static void DrawCoverRect(D3DTexture *boxArt, const Icon *icon, float x, float y, float w, float h, float radius,
                          float u1)
{
    if (boxArt != NULL)
    {
        const float fade = ArtFade(boxArt);
        if (fade < 1.0f)
            DrawCoverRect(NULL, icon, x, y, w, h, radius, u1);
        const D3DCOLOR tint = WithAlpha(0xFFFFFFFF, fade);
        TextureRound(boxArt, x, y, w, h, radius, 0.0f, 0.0f, u1, 1.0f, tint, tint);
        return;
    }

    if (icon != NULL && icon->average != NULL)
        TextureRound(icon->average, x, y, w, h, radius, 0.0f, 0.0f, u1, 1.0f, 0xFFFFFFFF, 0xFF808080);
    else
        FillRound(x, y, w, h, radius, COL_SURFACE_HI);

    if (icon != NULL && icon->texture != NULL)
        TextureRound(icon->texture, x, y, w, h, radius, 0.0f, 0.0f, u1, 1.0f, 0xFFFFFFFF, 0xFFFFFFFF);
}

static void DrawCoverSquare(D3DTexture *boxArt, const Icon *icon, float x, float y, float size)
{
    DrawCoverRect(boxArt, icon, x, y, size, size, R(4.0f), 1.0f);
}

// A cover filling the left end of a card whose corners are `radius`: rounded
// on the left to match it, square on the right where the card carries on.
// The shapes round all four corners, so it's drawn a radius wider and the
// right-hand ones clipped off.
static void DrawCoverFlushLeft(D3DTexture *boxArt, const Icon *icon, float x, float y, float size, float radius)
{
    const bool wasOn = g_clipOn;
    const RECT was = g_clipRect;
    SetClip(x, y, size, size);
    DrawCoverRect(boxArt, icon, x, y, size + radius, size, radius, (size + radius) / size);
    g_clipOn = wasOn;
    g_clipRect = was;
    ApplyClip(); // the device's scissor too, for whatever draws next
}

