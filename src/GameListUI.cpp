    view.subheading = subheading;
    view.labels = labels;
    view.sublabels = sublabels;
    view.sections = NULL;
    view.count = count;
    view.selected = 0;
    view.scroll = 0;
    view.focused = true;
    view.showCounter = false;

    UiHint hints[2];
