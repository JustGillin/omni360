// ---------------------------------------------------------------------------
// Shape shader: rounded rectangles, outlines, soft shadows and rings
// ---------------------------------------------------------------------------
//
// The dashboard look is built from rounded tiles and cards, a white ring
// round whatever has focus, a soft shadow under the focused tile and the
// storage ring - none of which a plain quad can draw. Rather than textures
// for each, one pixel shader works out how far each pixel is from the shape's
// edge (a signed distance: negative inside, positive outside) and turns that
// into coverage:
//
//   fill    - inside the shape, with one pixel of anti-aliasing at the edge
//   stroke  - a band of the given width just inside the edge (focus rings)
//   blur    - a falloff over that many pixels outside the edge (shadows,
//             drawn on a quad enlarged by the blur)
//   ring    - a circle's band instead of a box, coloured Tint for the share
//             of a turn given in RingParams.x, clockwise from the top, and
//             GradB for the rest (the storage ring)
//   line    - a line from one point to another with round ends, half as
//             thick as ShapeParams.y either side (the popup's tick - the font
//             has no tick to draw)
//
// Its own vertex shader, a copy of QuadVertexShader that also passes the
// pixel position through, so the proven quad pipeline is untouched. Where a
// shape is relative to is given as a constant (ShapeRect) rather than read
// from the texture coordinates, so a texture can be drawn with a cropped UV
// range and still have its corners rounded in the right place.
//
// Everything is lerp/step arithmetic with no branches, so the compiler has no
// flow control to get wrong; a shape costs a few dozen ALU ops a pixel.
static const char g_strShapeShader[] =
    "struct VS_IN\n"
    "{\n"
    "    float2 Pos : POSITION;\n"
    "    float2 Tex : TEXCOORD0;\n"
    "};\n"
    "struct VS_OUT\n"
    "{\n"
    "    float4 Position : POSITION;\n"
    "    float2 TexCoord0 : TEXCOORD0;\n"
    "    float2 Pixel : TEXCOORD1;\n"
    "};\n"
    "VS_OUT ShapeVertexShader( VS_IN In )\n"
    "{\n"
    "    VS_OUT Out;\n"
    "    Out.Position.x = In.Pos.x - 0.5;\n"
    "    Out.Position.y = In.Pos.y - 0.5;\n"
    "    Out.Position.z = 0.0;\n"
    "    Out.Position.w = 1.0;\n"
    "    Out.TexCoord0 = In.Tex;\n"
    "    Out.Pixel = In.Pos;\n"
    "    return Out;\n"
    "}\n"
    "uniform float4 Tint : register(c1);\n"
    "uniform float4 GradA : register(c2);\n"
    "uniform float4 GradB : register(c3);\n"
    "uniform float4 GradAxis : register(c4);\n"
    "uniform float4 ShapeRect : register(c5);\n"   // x, y, w, h in pixels
    "uniform float4 ShapeParams : register(c6);\n" // radius, stroke width (0 fills), blur (0 is crisp), 0 box / 1 ring / 2 line
    "uniform float4 RingParams : register(c7);\n"  // x: the ring's filled share of a turn
    "uniform float4 LineParams : register(c8);\n"  // a line's two ends, in pixels: (ax, ay, bx, by)
    "sampler QuadTexture : register(s0);\n"
    "float4 ShapePixelShader( VS_OUT In ) : COLOR0\n"
    "{\n"
    "    float2 halfSize = ShapeRect.zw * 0.5;\n"
    "    float2 local = In.Pixel - ShapeRect.xy;\n"
    "    float2 p = local - halfSize;\n"
    "    float r = ShapeParams.x;\n"
    "    float2 q = abs(p) - (halfSize - r);\n"
    "    float boxD = length(max(q, 0.0)) + min(max(q.x, q.y), 0.0) - r;\n"
    "    float len = length(p);\n"
    "    float ringD = max(len - halfSize.x, (halfSize.x - ShapeParams.y) - len);\n"
    "    float isLine = step(1.5, ShapeParams.w);\n"
    "    float isRing = step(0.5, ShapeParams.w) - isLine;\n"
    "    float2 pa = In.Pixel - LineParams.xy;\n"
    "    float2 ba = LineParams.zw - LineParams.xy;\n"
    "    float along = saturate(dot(pa, ba) / max(dot(ba, ba), 0.001));\n"
    "    float lineD = length(pa - ba * along) - ShapeParams.y * 0.5;\n"
    "    float d = lerp(lerp(boxD, ringD, isRing), lineD, isLine);\n"
    "    float fill = saturate(0.5 - d);\n"
    "    float stroke = fill * saturate(0.5 + d + ShapeParams.y);\n"
    "    float cover = lerp(fill, stroke, step(0.001, ShapeParams.y) * (1.0 - isRing - isLine));\n"
    "    float soft = saturate(1.0 - d / max(ShapeParams.z, 0.001));\n"
    "    cover = lerp(cover, soft * soft, step(0.001, ShapeParams.z));\n"
    "    float t = dot(saturate(local / ShapeRect.zw), GradAxis.xy);\n"
    "    float4 color = tex2D( QuadTexture, In.TexCoord0 ) * Tint * lerp( GradA, GradB, t );\n"
    "    float turn = frac(atan2(p.x, -p.y) / 6.2831853 + 1.0);\n"
    "    float used = step(turn, RingParams.x);\n"
    "    color = lerp(color, lerp(GradB, Tint, used), isRing);\n"
    "    color.a *= cover;\n"
    "    return color;\n"
    "}\n";

static D3DVertexShader *g_pShapeVertexShader = NULL;
static D3DPixelShader *g_pShapePixelShader = NULL;

// False if the shape shaders didn't compile - shapes then fall back to plain
// square quads (see DrawShape), so the UI loses its corners rather than
// failing to start.
static bool g_shapesReady = false;

static bool CompileShader(const char *entry, const char *profile, ID3DXBuffer **out)
{
    ID3DXBuffer *errors = NULL;
    HRESULT hr = D3DXCompileShader(g_strShapeShader, sizeof(g_strShapeShader) - 1,
                                   NULL, NULL, entry, profile, 0, out, &errors, NULL);
    if (FAILED(hr))
    {
        dprintf("[ui] %s didn't compile (0x%08lX): %s\n", entry, (unsigned long)hr,
                errors != NULL ? (const char *)errors->GetBufferPointer() : "no message");
    }
    if (errors != NULL)
        errors->Release();
    return SUCCEEDED(hr);
}

static void CreateShapeShaders()
{
    ID3DXBuffer *code = NULL;

    if (!CompileShader("ShapeVertexShader", "vs.2.0", &code))
        return;
    HRESULT hr = g_pd3dDevice->CreateVertexShader((DWORD *)code->GetBufferPointer(), &g_pShapeVertexShader);
    code->Release();
    if (FAILED(hr))
        return;

    if (!CompileShader("ShapePixelShader", "ps.2.0", &code))
        return;
    hr = g_pd3dDevice->CreatePixelShader((DWORD *)code->GetBufferPointer(), &g_pShapePixelShader);
    code->Release();
    if (FAILED(hr))
        return;

    g_shapesReady = true;
}

static bool CreateQuadResources()
{
    static const D3DVERTEXELEMENT9 decl[] =
        {
            {0, 0, D3DDECLTYPE_FLOAT2, D3DDECLMETHOD_DEFAULT, D3DDECLUSAGE_POSITION, 0},
            {0, 8, D3DDECLTYPE_FLOAT2, D3DDECLMETHOD_DEFAULT, D3DDECLUSAGE_TEXCOORD, 0},
            D3DDECL_END()};

    if (FAILED(g_pd3dDevice->CreateVertexDeclaration(decl, &g_pQuadVertexDecl)))
        return false;

    ID3DXBuffer *pShaderCode = NULL;

    if (FAILED(D3DXCompileShader(g_strQuadShader, sizeof(g_strQuadShader) - 1,
                                 NULL, NULL, "QuadVertexShader", "vs.2.0", 0, &pShaderCode, NULL, NULL)))
        return false;

    HRESULT hr = g_pd3dDevice->CreateVertexShader((DWORD *)pShaderCode->GetBufferPointer(), &g_pQuadVertexShader);
    pShaderCode->Release();
    if (FAILED(hr))
        return false;

    if (FAILED(D3DXCompileShader(g_strQuadShader, sizeof(g_strQuadShader) - 1,
                                 NULL, NULL, "QuadPixelShader", "ps.2.0", 0, &pShaderCode, NULL, NULL)))
        return false;

    hr = g_pd3dDevice->CreatePixelShader((DWORD *)pShaderCode->GetBufferPointer(), &g_pQuadPixelShader);
    pShaderCode->Release();
    if (FAILED(hr))
        return false;

    // 1x1 white texture so DrawRect() can go through the exact same textured
    // draw path as icons, just with a solid-color texture and a tint.
    if (FAILED(g_pd3dDevice->CreateTexture(1, 1, 1, 0, D3DFMT_A8R8G8B8, D3DPOOL_MANAGED, &g_pWhiteTexture, NULL)))
        return false;

    D3DLOCKED_RECT lr;
    if (SUCCEEDED(g_pWhiteTexture->LockRect(0, &lr, NULL, 0)))
    {
        *(DWORD *)lr.pBits = 0xFFFFFFFF;
        g_pWhiteTexture->UnlockRect(0);
    }

    if (!CreateButtonAtlas())
        return false;

    return true;
}

// ---------------------------------------------------------------------------
// Textures built from pixels
// ---------------------------------------------------------------------------
//
// An older comment on the gradient shader said hand-filling a texture was off
// the table because the GPU's tiling makes a naive linear LockRect write wrong
// for anything above 1x1. That is true of the TILED formats - but the XDK also
// exposes linear ones, where memory really is row after row and a
// straightforward write is correct.

// Builds a texture from decoded pixels (0xAARRGGBB, row-major): the button
// atlas below, the cover thumbnails D3DX won't take, and the box art and Store
// art the workers decode. D3DFMT_LIN_A8R8G8B8
// is laid out row after row, so a plain write through LockRect is correct.
// Rows go through lr.Pitch rather than assuming width * 4, since the GPU pads
// linear rows.
//
// Kept at the source size, never resampled: a thumbnail's 64x64, a tile at
// most 512x512, a wallpaper 1280x720.
static D3DTexture *CreateTextureFromArgb(const unsigned long *pixels, unsigned long w, unsigned long h)
{
    D3DTexture *tex = NULL;
    if (FAILED(g_pd3dDevice->CreateTexture(w, h, 1, 0, D3DFMT_LIN_A8R8G8B8, D3DPOOL_MANAGED, &tex, NULL)))
        return NULL;

    D3DLOCKED_RECT lr;
    if (FAILED(tex->LockRect(0, &lr, NULL, 0)))
    {
        tex->Release();
        return NULL;
    }

    // A row at a time: texture memory takes long sequential writes best.
    for (unsigned long y = 0; y < h; ++y)
        memcpy((BYTE *)lr.pBits + y * lr.Pitch, pixels + y * w, w * sizeof(DWORD));

    tex->UnlockRect(0);
    return tex;
}

// The footer's button icons. The art is pre-rendered by
// tools/make_button_atlas.py and compiled in as PNG bytes, then decoded by the
// same in-house decoder that rescues the cover thumbnails - so there is no
// file to deploy beside the XEX, and no dependence on which PNGs D3DX takes.
static bool CreateButtonAtlas()
{
    unsigned long *pixels = NULL;
    unsigned long w = 0, h = 0;
    const char *error = NULL;

    if (!PngDecodeToArgb(kButtonAtlasPng, kButtonAtlasPngSize, &pixels, &w, &h, &error))
    {
        dprintf("[ui] button atlas would not decode: %s\n", error != NULL ? error : "?");
        return false;
    }

    g_pButtonAtlas = CreateTextureFromArgb(pixels, w, h);
    PngFree(pixels);

    return g_pButtonAtlas != NULL;
}

// A rectangle quads are cut to, while one is set - for a page that scrolls
// under its header and footer. Every quad draw sets the scissor state from
// this, since each sets the device's state in full. Text isn't cut: a page
// that clips leaves out any line that isn't wholly inside (TextInClip).
static bool g_clipOn = false;
static RECT g_clipRect;

static void SetClip(float x, float y, float w, float h)
{
    g_clipOn = true;
    g_clipRect.left = (LONG)x;
    g_clipRect.top = (LONG)y;
    g_clipRect.right = (LONG)(x + w);
    g_clipRect.bottom = (LONG)(y + h);
}

static void ClearClip()
{
    g_clipOn = false;
}

static void ApplyClip()
{
    if (g_clipOn)
    {
        g_pd3dDevice->SetScissorRect(&g_clipRect);
        g_pd3dDevice->SetRenderState(D3DRS_SCISSORTESTENABLE, TRUE);
    }
    else
    {
        g_pd3dDevice->SetRenderState(D3DRS_SCISSORTESTENABLE, FALSE);
    }
}

// Whether a line of text from y to y + h is wholly inside the clip.
static bool TextInClip(float y, float h)
{
    return !g_clipOn || (y >= (float)g_clipRect.top && y + h <= (float)g_clipRect.bottom);
}

// D3DCOLOR (ARGB) -> the float4 the pixel shader constants expect.
static void ColorToFloat4(D3DCOLOR c, float *out)
{
    out[0] = ((c >> 16) & 0xFF) / 255.0f; // R
    out[1] = ((c >> 8) & 0xFF) / 255.0f;  // G
    out[2] = (c & 0xFF) / 255.0f;         // B
    out[3] = ((c >> 24) & 0xFF) / 255.0f; // A
}

// Core quad draw. gradA/gradB/vertical describe the two-stop gradient the
// pixel shader applies on top of tint; pass the same color for both to get a
// flat fill (which is what DrawQuad/DrawRect below do).
static void DrawQuadUV(D3DTexture *texture, float x, float y, float w, float h,
                       float u0, float v0, float u1, float v1,
                       D3DCOLOR tint, D3DCOLOR gradA, D3DCOLOR gradB, bool vertical)
{
    float tintF[4];
    float gradAF[4];
    float gradBF[4];
    ColorToFloat4(tint, tintF);
    ColorToFloat4(gradA, gradAF);
    ColorToFloat4(gradB, gradBF);

    float axis[4] = {vertical ? 0.0f : 1.0f, vertical ? 1.0f : 0.0f, 0.0f, 0.0f};

    // Tint is declared "register(c1)" inside QuadPixelShader, not the vertex
    // shader - vertex and pixel shader constants are separate register
    // banks in D3D9. Setting it as a vertex constant left the pixel shader's
    // real c1 at its default (0,0,0,0), multiplying every quad's sampled
    // color to fully transparent black - every DrawQuad/DrawRect call
    // (icons, placeholders, the selection highlight) was invisible. The
    // gradient constants below live in the same pixel-shader bank for the
    // same reason.
    g_pd3dDevice->SetPixelShaderConstantF(1, tintF, 1);
    g_pd3dDevice->SetPixelShaderConstantF(2, gradAF, 1);
    g_pd3dDevice->SetPixelShaderConstantF(3, gradBF, 1);
    g_pd3dDevice->SetPixelShaderConstantF(4, axis, 1);

    g_pd3dDevice->SetTexture(0, texture != NULL ? texture : g_pWhiteTexture);
    g_pd3dDevice->SetVertexDeclaration(g_pQuadVertexDecl);
    g_pd3dDevice->SetVertexShader(g_pQuadVertexShader);
    g_pd3dDevice->SetPixelShader(g_pQuadPixelShader);

    // Explicit, complete state setup - matching Font::DrawText's own list in
    // Common/AtgFont.cpp (the only other proven-working dynamic 2D draw in
    // this project) rather than the handful of blend states this function
    // set before. Leaving the rest at whatever was last inherited (e.g.
    // Z-test enabled with no properly-configured depth buffer for this draw,
    // which Console's own RenderBackground() explicitly turns on) is a very
    // plausible way to fault the GPU exactly like we were seeing.
    g_pd3dDevice->SetRenderState(D3DRS_ALPHABLENDENABLE, TRUE);
    g_pd3dDevice->SetRenderState(D3DRS_SRCBLEND, D3DBLEND_SRCALPHA);
    g_pd3dDevice->SetRenderState(D3DRS_DESTBLEND, D3DBLEND_INVSRCALPHA);
    g_pd3dDevice->SetRenderState(D3DRS_BLENDOP, D3DBLENDOP_ADD);
    g_pd3dDevice->SetRenderState(D3DRS_ALPHATESTENABLE, FALSE);
    g_pd3dDevice->SetRenderState(D3DRS_FILLMODE, D3DFILL_SOLID);
    g_pd3dDevice->SetRenderState(D3DRS_CULLMODE, D3DCULL_NONE); // don't cull our quad regardless of winding
    g_pd3dDevice->SetRenderState(D3DRS_ZENABLE, FALSE);
    g_pd3dDevice->SetRenderState(D3DRS_STENCILENABLE, FALSE);
    g_pd3dDevice->SetRenderState(D3DRS_VIEWPORTENABLE, FALSE); // matches our manual pixel->clip-space math in the vertex shader
    // TEMPORARY diagnostic fix: a full-screen test quad rendered completely
    // invisible (not mispositioned - literally nothing), which is the classic
    // symptom of D3DRS_COLORWRITEENABLE being masked to 0 by something else
    // and never explicitly restored here. Also disabling scissor test in
    // case a leftover zero-area scissor rect is in play.
    g_pd3dDevice->SetRenderState(D3DRS_COLORWRITEENABLE, 0x0000000F); // all 4 channels (R,G,B,A)
    ApplyClip();
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_MINFILTER, D3DTEXF_LINEAR);
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_MAGFILTER, D3DTEXF_LINEAR);
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_MIPFILTER, D3DTEXF_NONE); // all our textures (icons + the 1x1 white) are single-mip now
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_ADDRESSU, D3DTADDRESS_CLAMP);
    g_pd3dDevice->SetSamplerState(0, D3DSAMP_ADDRESSV, D3DTADDRESS_CLAMP);

    // Xbox 360 needs vertex data submitted through BeginVertices/EndVertices
    // (writing directly into write-combined GPU ring-buffer memory), not
    // DrawPrimitiveUP from a plain CPU array the way PC D3D9 code typically
    // does - confirmed against Common/AtgFont.cpp's Font::DrawText, the one
    // piece of proven-working dynamic-geometry code in this project. Per its
    // own comments: writes must go in ascending address order, and never
    // with anything smaller than a 32-bit store - both satisfied here since
    // we're writing consecutive floats.
    //
    // Also matching Font::DrawText's exact primitive choice: D3DPT_QUADLIST
    // (a native Xbox 360 GPU primitive with no PC D3D9 equivalent) with
    // vertices in TL, TR, BR, BL order - not D3DPT_TRIANGLESTRIP, which is
    // what an earlier version of this function used and still crashed the
    // GPU even after switching to BeginVertices/EndVertices.
    volatile FLOAT *pVertex;
    HRESULT hr = g_pd3dDevice->BeginVertices(D3DPT_QUADLIST, 4, sizeof(QuadVertex), (VOID **)&pVertex);
    if (SUCCEEDED(hr))
    {
        pVertex[0] = x;         pVertex[1] = y;         pVertex[2] = u0;  pVertex[3] = v0;  // TL
        pVertex[4] = x + w;     pVertex[5] = y;         pVertex[6] = u1;  pVertex[7] = v0;  // TR
        pVertex[8] = x + w;     pVertex[9] = y + h;     pVertex[10] = u1; pVertex[11] = v1; // BR
        pVertex[12] = x;        pVertex[13] = y + h;    pVertex[14] = u0; pVertex[15] = v1; // BL

        g_pd3dDevice->EndVertices();
    }
    else
    {
        // TEMPORARY: this branch was previously silent - if BeginVertices
        // itself fails at runtime, we'd skip drawing entirely with zero
        // indication why, which would perfectly explain "nothing renders,
        // nothing crashes".
        static bool loggedFailure = false;
        if (!loggedFailure)
        {
            loggedFailure = true;
            dprintf("[DIAG] BeginVertices FAILED, hr=0x%08X\n", hr);
        }
    }

    g_pd3dDevice->SetTexture(0, NULL);
    g_pd3dDevice->SetVertexDeclaration(NULL);
    g_pd3dDevice->SetVertexShader(NULL);
    g_pd3dDevice->SetPixelShader(NULL);
}

