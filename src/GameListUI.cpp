{
    float x, y, w, h;
};

static TilePill PillFor(const char *label, float tileX, float tileY, float tileS)
{
    TilePill p;
    p.h = S(24.0f);
    p.w = TextWidth(label, 0.56f, true) + S(18.0f);
    p.x = tileX + tileS - p.w - S(10.0f);
    p.y = tileY + S(10.0f);
    return p;
}

