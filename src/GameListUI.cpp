#define MAX_STORE_ART 16
#define STORE_SHADE   0xC7000000 // the foot of a featured tile, under its name

// The wallpapers and screenshots on show. A game page holds five; when
// there's no room, the one drawn longest ago goes.
struct StoreArtTexture
{
    unsigned long titleId;
    StoreArtKind kind;
    D3DTexture *texture;
    float width, height;
    unsigned long lastUsed; // g_storeFrame
};

static StoreArtTexture g_storeArt[MAX_STORE_ART];
static int g_storeArtCount = 0;

// The front page's wallpapers asked for - the featured tiles' and the
// Collections cards' on screen - so they're asked for again only when that
// changes, or when a game page may have pushed them out.
#define MAX_PAGE_ART (STORE_FEATURED_MAX + STORE_COLLECTIONS_MAX)
static unsigned long g_pageArtAsked[MAX_PAGE_ART];
static int g_pageArtAskedCount = -1; // -1: ask again whatever's missing

// Marks it as in use.
static const StoreArtTexture *StoreArtFor(unsigned long titleId, StoreArtKind kind)
{
    for (int i = 0; i < g_storeArtCount; ++i)
    {
        if (g_storeArt[i].titleId == titleId && g_storeArt[i].kind == kind)
        {
            g_storeArt[i].lastUsed = g_storeFrame;
            return &g_storeArt[i];
        }
    }
    return NULL;
}

static void ReleaseStoreArt()
{
    for (int i = 0; i < g_storeArtCount; ++i)
    {
        if (g_storeArt[i].texture != NULL)
            g_storeArt[i].texture->Release();
    }
    g_storeArtCount = 0;
    g_pageArtAskedCount = -1;
    ReleaseStoreCovers();
}

// Asks for the wallpapers in want - those on the page that aren't loaded -
// that weren't wanted last frame: one still on its way isn't asked again as
// the others arrive, and one pushed out is asked for once it's missed.
static void RequestMissingPageArt(const unsigned long *want, int wantCount)
{
    for (int i = 0; i < wantCount; ++i)
    {
        bool asked = false;
        for (int j = 0; j < g_pageArtAskedCount && !asked; ++j)
            asked = (g_pageArtAsked[j] == want[i]);
        if (!asked)
            RequestStoreArt(want[i], STORE_ART_BACKGROUND);
    }
    memcpy(g_pageArtAsked, want, wantCount * sizeof(want[0]));
    g_pageArtAskedCount = wantCount;
}

void PumpStoreArt()
{
    if (!g_Initialized)
        return;

    StoreArtData data;
    if (!TakeStoreArt(&data))
        return;

    if (StoreArtFor(data.titleId, data.kind) != NULL)
    {
        free(data.pixels);
        return;
    }

    // Decoded on the worker - a screenshot at half size already - so this
    // is only the copy into a texture.
    const double started = TimerMs();
    D3DTexture *texture = CreateTextureFromArgb(data.pixels, data.width, data.height);
    free(data.pixels);
    const double took = TimerMs() - started;
    if (took >= IMAGE_TIMING_LOG_MS)
        dprintf("[timing] %s %08lX (%dx%d): texture %.1f ms\n", data.kind >= STORE_ART_SCREEN ? "screenshot" : "wallpaper",
                data.titleId, data.width, data.height, took);
    if (texture == NULL)
        return;

    int slot = g_storeArtCount;
    if (slot >= MAX_STORE_ART)
    {
        slot = 0;
        for (int i = 1; i < g_storeArtCount; ++i)
        {
            if (g_storeArt[i].lastUsed < g_storeArt[slot].lastUsed)
                slot = i;
        }
        g_storeArt[slot].texture->Release();
    }
    else
    {
        g_storeArtCount++;
    }

    StoreArtTexture &art = g_storeArt[slot];
    art.titleId = data.titleId;
    art.kind = data.kind;
    art.texture = texture;
    NoteArtArrived(texture);
    art.width = (float)data.width;
    art.height = (float)data.height;
    art.lastUsed = g_storeFrame;
}

// What an A to Z tile says: its letter, or "All".
static const char *LetterTileLabel(char letter)
{
    static char labels[256][2];
    if (letter == STORE_LETTER_ALL)
        return "All";
    labels[(unsigned char)letter][0] = letter;
    return labels[(unsigned char)letter];
}

